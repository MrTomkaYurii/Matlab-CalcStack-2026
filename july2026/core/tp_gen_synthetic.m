function IMG = tp_gen_synthetic(CFG)
% TP_GEN_SYNTHETIC  Будує синтетичне поляризоване спекл-поле.
%   Дає таку саму вкладену структуру зображень, що й реальне вимірювання,
%   тож увесь конвеєр працює наскрізь без жодних виміряних даних.
%
%   IMG.(inPol).(analyzer) : N x N double у [0,1]
%       inPol    у {'in0','in45','in90','inRC'}   (освітлення)
%       analyzer у {'I0','I45','I90','I135','Iliv','Iprav'}
%
%   Модель: для кожного освітлення синтезуємо цілком розвинене спеклове
%   джонсове поле (Ex,Ey) як просторово-корельований комплексний гаусів шум,
%   а тоді формуємо шість поляризаційних інтенсивностей із узгоджених
%   співвідношень Стокса.

N  = CFG.crop.size;
L  = CFG.synth.corrLen;
rng(CFG.synth.seed);

inPols = {'in0','in45','in90','inRC'};
% Різні геометрії освітлення -> різне джонсове змішування, тож 16 f_ik
% виходять справді різними (не виродженими).
mix = [ 1.0 0.0 ;    % in0  : переважно x
        0.7 0.7 ;    % in45 : збалансовано
        0.0 1.0 ;    % in90 : переважно y
        1.0 1i  ];   % inRC : права циркулярна

IMG = struct();
for p = 1:numel(inPols)
    Ex = speckle(N, L) * mix(p,1);
    Ey = speckle(N, L) * mix(p,2);

    I0    = abs(Ex).^2;
    I90   = abs(Ey).^2;
    I45   = 0.5 * abs(Ex + Ey).^2;
    I135  = 0.5 * abs(Ex - Ey).^2;
    Iprav = 0.5 * abs(Ex - 1i*Ey).^2;   % права циркулярна
    Iliv  = 0.5 * abs(Ex + 1i*Ey).^2;   % ліва  циркулярна

    S = struct('I0',I0,'I45',I45,'I90',I90,'I135',I135,'Iliv',Iliv,'Iprav',Iprav);
    fn = fieldnames(S);
    for f = 1:numel(fn)           % нормуємо кожен канал до [0,1], як /255
        v = S.(fn{f});
        v = v - min(v(:));
        m = max(v(:)); if m > 0, v = v / m; end
        S.(fn{f}) = v;
    end
    IMG.(inPols{p}) = S;
end
end

% ------------------------------------------------------------------------
function A = speckle(N, L)
% Цілком розвинений спекл: низькочастотно відфільтрований комплексний білий шум.
G = (randn(N) + 1i*randn(N));
[u,v] = meshgrid(-floor(N/2):ceil(N/2)-1);
H = exp(-(u.^2 + v.^2) / (2*(N/(2*pi*L))^2));  % гаусів ФНЧ
A = ifft2(ifftshift(fftshift(fft2(G)).*H));
end
