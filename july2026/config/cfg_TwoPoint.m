function CFG = cfg_TwoPoint()
% CFG_TWOPOINT  Єдине джерело всіх налаштувань конвеєра двоточкового аналізу.
%   Тут зібрані всі параметри. Щоб розширити конвеєр, зазвичай достатньо
%   відредагувати лише цей файл (додати зразок, увімкнути алгоритм, стиль
%   візуалізації) і, щонайбільше, додати один новий модуль у viz/ чи core/.
%
%   Повертає вкладену структуру CFG, яку споживає run_TwoPoint_Pipeline.

CFG = struct();

% ------------------------------------------------------------------ шляхи
% УВАГА (серпень 2026): теки перейменовано на диску.
%   Стара структура (zrazok_1/zrazok_2, формат 0-0.bmp,0-45.bmp,...) тепер тут:
%   "Зразки - старі"  /  "Реальні БТ (старі) - Розрахунки"
%   Нова структура (Мозг1,Мозг2,..., формат e0x.bmp,e0y.bmp,...) — тут:
%   "Зразки - нові (серпень 2026)"  /  "Реальні БТ (нові) - Розрахунки"
%   (новий формат ще не підтримано в tp_load_images.m — фізичний сенс
%   x/y/освітлення не з'ясовано остаточно).
CFG.paths.readRoot = 'C:\July 2026-Results\Зразки - старі';            % де лежать зразки
CFG.paths.saveRoot = 'C:\July 2026-Results\Реальні БТ (старі) - Розрахунки - 07-2026'; % куди
                                                                 % писати результати (створюється сама)
CFG.paths.example  = 'zrazok_1';  % запасний варіант (для одиничних тестового/сим. проходів)
% examples — МАСИВ підтек, які основний пайплайн обробляє для КОЖНОГО зразка
%   (у кожного зразка в Зразки - старі\<sample>\ лежать zrazok_1, zrazok_2).
%   Результати кожної пари (зразок, підтека) розкладаються в окрему теку:
%   saveRoot\<sample>\<example>\<algorithm>\...  (створюється автоматично).
CFG.paths.examples = {'zrazok_1', 'zrazok_2'};

% ------------------------------------------------------ джерело даних
% 'synthetic' -> згенерувати спекл-поле на льоту (дані не потрібні)
% 'real'      -> читати BMP поляризаційні зображення з readRoot\<зразок>\<example>
CFG.source  = 'real';
% повний перелік зразків (Зразки - старі\<sample>\zrazok_1, zrazok_2)
CFG.samples = {'Печінка','Плазма','Простата','Синовіальна рідина','Шийка матки'};
% ------------------------------------------------------------------- обрізка
CFG.crop.size = 500;   % квадратна вирізка N x N
CFG.crop.x0   = 1;     % початок (стовпець) верхнього лівого кута
CFG.crop.y0   = 1;     % початок (рядок) верхнього лівого кута

% ----------------------------------------------------- вибір алгоритму
% Будь-яка підмножина {'orthogonal','generalized'}; обидва — якщо обидва в списку.
CFG.algorithms = {'generalized'};%{'orthogonal','generalized'};

% ----------------------------------------- елементи матриці Мюллера f_ik
% Типово: усі 16. Звузьте, напр. до {'f11','f22','f33','f44'}, для швидкості.
els = cell(1,16); c = 0;
for i = 1:4
    for k = 1:4
        c = c + 1; els{c} = sprintf('f%d%d', i, k);
    end
end
CFG.elements = els;

    % --------------------------------------- параметри ОРТОГОНАЛЬНОГО алгоритму
    % За документом "+Ортогонально-направленний..._x_y":
    %   для кожної r1 скануємо r2 уздовж X (d,0) та уздовж Y (0,d), без діагоналей.
    %   OX та OY рахуються й подаються окремо (без злиття).
    %   ОКРЕМА карта будується для кожного рознесення d зі списку нижче (типово —
    %   діадичний багатомасштабний набір). Вихідні напрями: OX_step_1 ... OY_step_16.
    CFG.ortho.steps   = [32 16 8 4 2 1];  % КРОКИ (відстані) між точками для OX/OY (окремо від gen)
    CFG.ortho.posStep = 1;             % ПРОРІДЖЕННЯ перших точок (1 => усі пікселі; >1 => рідша карта)
    CFG.ortho.directions = {'OX','OY'}; % які напрями рахувати; звузьте до {'OY'} чи {'OX'},
                                        % щоб перерахувати лише один (не чіпаючи інший)

    % --------------------------------------- параметри УЗАГАЛЬНЕНОГО алгоритму
    % За документом "Обобщённый_алгоритм_двухточечного_сканирования".
    % ДВІ НЕЗАЛЕЖНІ ЗМІННІ:
    %
    % steps — МАСИВ кроків: на КОЖЕН крок будується окрема ρ-діаграма у своїй теці
    %   (generalized\step_1\, step_2\, ...). Крок = крок сітки рознесень.
    CFG.gen.steps    = [32 16 8 4 2 1];  % масив кроків (кожен -> тека step_N)
    CFG.gen.posStep  = 1;    % прорідження перших точок (1 => усі пікселі)
    % Автоправило: якщо в CFG.gen.steps є крок = 1 (найважчий випадок, найгустіша
    % сітка), прорідження для НЬОГО автоматично піднімається щонайменше до 2
    % (max(posStep,2)); решта кроків використовують posStep як задано вище.
    CFG.gen.maxDist  = [];   % макс. відстань (px); [] => N-1 (повний діапазон)
    CFG.gen.excludeZero = true;  % відкинути нульову відстань (0,0)
    CFG.gen.parallel    = true;  % паралельний розрахунок (parfor, усі ядра) — для 5800H

% ------------------------------------------------------ контроль якості
% Якщо розподіл вироджений — він НЕ зберігається (згідно з вимогою).
CFG.qc.enable     = true;
CFG.qc.maxNaNfrac = 0.60;  % пропустити, якщо частка NaN більша за це
CFG.qc.minStd     = 1e-9;  % пропустити майже сталі карти

% ----------------------------------------------- перемикачі візуалізації
% Layout фігур — за ескізом (варфрейми); стиль — за old/calc_2025_vis_DvotMM.
CFG.viz.colormaps   = {'jet','gray'}; % цикл колірних мап (як у старому коді)
CFG.viz.parallel    = true;   % розпаралелити побудову графіків по f_ik (parfor, усі ядра);
                              % найповільніший етап (16 елементів × 7 подань) — раніше йшов
                              % на одному ядрі. false => послідовно (як було раніше)
CFG.viz.overview    = true;   % Частина 01: сітки 4x4 (усі 16 f_ik) на рівні кроку
CFG.viz.mapsHist    = true;   % (1) на елемент: 2x2 карти + гістограми (мод+арг)
CFG.viz.surfContour = true;   % (2) на елемент: 2x2 3D-поверхні + контурні карти
CFG.viz.contour3    = true;   % (2b) на елемент: контурні лінії у 3D (contour3)
CFG.viz.wavelet     = true;   % (3) на елемент: вейвлет W(a,b) (мод+арг)
CFG.viz.acfPsd      = true;   % (4A) на елемент: 2D АКФ + 2D PSD (мод+арг)
CFG.viz.acfCuts     = true;   % (4B) на елемент: 1D перерізи ACF + їх PSD (log-log)
CFG.viz.skeleton    = true;   % (5) на елемент: вейвлет-скелетон + гістограма максимумів
CFG.viz.levelBands  = true;   % (6) на елемент: смуговий аналіз концентрації біля рівнів
                              % (маска + гістограма, окремо мод/арг), доповнює (2)
CFG.viz.bandLevels   = 8;     % кількість рівнів для (6) (рівномірно між min і max)
CFG.viz.bandWidthPct = 0.02;  % ширина смуги = ця частка від діапазону (max-min)
CFG.viz.histBins      = 50;   % кількість стовпців гістограми
CFG.viz.contourLevels = 6;    % кількість рівнів контурів (з підписами %.2f)
CFG.viz.contourSmoothPx = 3;  % σ (px) NaN-безпечного згладжування ЛИШЕ для ліній
                              % контуру (viz_sections) — на реальних шумних даних
                              % лінії інакше рвуться на плями. 0 = вимкнено (сирі
                              % дані); карти/гістограми/3D/АКФ/вейвлет не чіпаються

% ---- (4) АКФ + PSD -----------------------------------------------------
% Два підходи (обираєш тут):
%   'fast'   — Wiener–Khinchin: PSD = |FFT|^2, ACF = IFFT(PSD). Швидко.
%   'direct' — як рахується: ACF = xcorr2 (прямо), PSD = |FFT(ACF)|^2. Повільно.
CFG.acf.method = 'fast';

CFG.wavelet.name            = 'amor';   % аналітичний вейвлет Морле
CFG.wavelet.voicesPerOctave = 12;
CFG.wavelet.highlightScales = [10 50];  % a=10 (червона), a=50 (синя)
CFG.wavelet.scaleRange      = [1 100];  % показувати лише масштаби a в цьому інтервалі
                                        % (вище ~65 зазвичай сенсу не має; можна [1 65])
CFG.wavelet.profile         = 'center_row'; % 'center_row'|'center_col'|'mean_row'
CFG.wavelet.onArg           = true;     % також перетворювати профіль аргументу

% ----------------------------------------------------------- вихід/рендер
CFG.out.format     = 'png';
CFG.out.dpi        = 200;
CFG.out.closeAfter = true;   % закривати фігури після збереження (пакетний режим)

% ---------------------- фізична симуляція БТ (source = 'synthetic') -----
% Двопроменезаломна тканина: орієнтація осі theta(x,y) + затримка delta(x,y)
% + когерентний спекл. Усі 24 зображення — через один джонсів оператор.
CFG.sim.axisCorrLen    = 40;      % довжина кореляції орієнтації осі (px) — «архітектоніка»
CFG.sim.retCorrLen     = 30;      % довжина кореляції затримки (px)
CFG.sim.speckleCorrLen = 6;       % довжина кореляції спеклу (px)
CFG.sim.retMin         = 0;       % мін. затримка (рад)
CFG.sim.retMax         = pi;      % макс. затримка (рад) — сила двопроменезаломлення
CFG.sim.seed           = 7;       % зерно ГВЧ для відтворюваності

% (застаріле) простий генератор tp_gen_synthetic — не використовується
CFG.synth.corrLen = 12;
CFG.synth.seed    = 7;
end
