function OUT = tp_B1_LB_0_90(f34, f43)
% TP_B1_LB_0_90  Блок B.1 (зелена формула, Word стор.1): LB_{0,90} = ln(f34/f43).
%   Незалежний блок — жодних залежностей від інших файлів Кроку B.
%   Імена змінних = позначення з Word ("Загальна формула для логарифма
%   відношення LB_{0,90}"), щоб порівнювати рядок-в-рядок:
%
%       Word                         код
%       f^c_34, f^c_43               f34, f43         (вхід, Крок A)
%       dA_34^{RC,LC}                dA34_RCLC        = Re(f34)
%       dB_34^{RC,LC}                dB34_RCLC        = Im(f34)
%       dA_43^{45,135}               dA43_45_135      = Re(f43)
%       dB_43^{45,135}               dB43_45_135      = Im(f43)
%       Re_{34,43}, Im_{34,43}       Re_34_43, Im_34_43
%       |LB_{0,90}|, arg[LB_{0,90}]  absLB_0_90, argLB_0_90
%   (Верхні індекси RC,LC / 45,135 у Word — з яких освітлень зібрано f34 і
%   f43; це робить Крок A (tp_fik_pair.m), тут беремо готові f34, f43.)
%
%   Вхід : f34, f43 — комплексні (число або 2D-карта, з tp_fik_pair.m).
%   Вихід: OUT = struct('mod',|LB_0,90|, 'arg',arg[LB_0,90], 'cplx',Re+i*Im)
%
%   Ділення на нуль (знаменник dA43^2+dB43^2 = 0): СВІДОМО без епсилона —
%   IEEE-754 дає NaN/Inf без помилки, візуалізація нижче відфільтровує їх
%   через isfinite(...).

% Захист від мовчазного неявного розширення (N×1 з 1×N -> N×N): розміри мусять збігатися.
assert(isequal(size(f34), size(f43)), 'tp_B1_LB_0_90: f34 і f43 мають бути одного розміру');

% f^c_mn = dA_mn + i*dB_mn   =>   dA = Re(f), dB = Im(f)
dA34_RCLC   = real(f34);    dB34_RCLC   = imag(f34);
dA43_45_135 = real(f43);    dB43_45_135 = imag(f43);

% Re_{34,43} = 1/2 * ln( ( (dA34)^2 + (dB34)^2 ) / ( (dA43)^2 + (dB43)^2 ) )
Re_34_43 = 0.5 * log( (dA34_RCLC.^2 + dB34_RCLC.^2) ./ (dA43_45_135.^2 + dB43_45_135.^2) );

% Im_{34,43} = atan2( dB34*dA43 - dA34*dB43  /  dA34*dA43 + dB34*dB43 )
%   (дріб під atan2 у Word = двоаргументний atan2(чисельник, знаменник))
Im_34_43 = atan2( dB34_RCLC.*dA43_45_135 - dA34_RCLC.*dB43_45_135, ...
                  dA34_RCLC.*dA43_45_135 + dB34_RCLC.*dB43_45_135 );

% |LB_{0,90}| = sqrt( (Re_{34,43})^2 + (Im_{34,43})^2 )
absLB_0_90 = sqrt( Re_34_43.^2 + Im_34_43.^2 );

% arg[LB_{0,90}] = atan2( Im_{34,43} / Re_{34,43} )
argLB_0_90 = atan2( Im_34_43, Re_34_43 );

% LB_{0,90} = Re_{34,43} + i*Im_{34,43}
OUT = struct('mod', absLB_0_90, 'arg', argLB_0_90, 'cplx', Re_34_43 + 1i*Im_34_43);
end
