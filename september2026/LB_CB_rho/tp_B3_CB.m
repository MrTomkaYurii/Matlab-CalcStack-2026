function OUT = tp_B3_CB(f23, f32)
% TP_B3_CB  Блок B.3 (зелена формула, Word стор.2): CB = ln(f23/f32).
%   Незалежний блок — жодних залежностей від інших файлів Кроку B.
%   Імена змінних = позначення з Word, щоб порівнювати рядок-в-рядок:
%
%       Word                             код
%       f^c_23, f^c_32                   f23, f32         (вхід, Крок A)
%       dA_23^{45,135}, dB_23^{45,135}   dA23_45_135, dB23_45_135   = Re(f23), Im(f23)
%       dA_32^{0,90},   dB_32^{0,90}     dA32_0_90,   dB32_0_90     = Re(f32), Im(f32)
%       Re_{23,32}, Im_{23,32}           Re_23_32, Im_23_32
%       |CB|, arg[CB]                    absCB, argCB
%   (Верхні індекси 45,135 / 0,90 у Word — з яких освітлень зібрано f23 і
%   f32; це робить Крок A (tp_fik_pair.m), тут беремо готові f23, f32.)
%
%   УВАГА (одруківка у Word): у першому рядку виводу CB у чисельнику й
%   знаменнику стоять індекси 34/43 (dA_34^{45,135} / dA_43^{0,90}); усі
%   наступні рядки (Re_{23,32}, Im_{23,32}) і сама CB = ln(f23/f32) — 23/32.
%   Реалізовано 23/32.
%
%   Вхід : f23, f32 — комплексні (число або 2D-карта, з tp_fik_pair.m).
%   Вихід: OUT = struct('mod',|CB|, 'arg',arg[CB], 'cplx',Re+i*Im)
%
%   Ділення на нуль: СВІДОМО без епсилона (IEEE-754 NaN/Inf, далі isfinite).

% Захист від мовчазного неявного розширення (N×1 з 1×N -> N×N): розміри мусять збігатися.
assert(isequal(size(f23), size(f32)), 'tp_B3_CB: f23 і f32 мають бути одного розміру');

% f^c_mn = dA_mn + i*dB_mn   =>   dA = Re(f), dB = Im(f)
dA23_45_135 = real(f23);    dB23_45_135 = imag(f23);
dA32_0_90   = real(f32);    dB32_0_90   = imag(f32);

% Re_{23,32} = 1/2 * ln( ( (dA23)^2 + (dB23)^2 ) / ( (dA32)^2 + (dB32)^2 ) )
Re_23_32 = 0.5 * log( (dA23_45_135.^2 + dB23_45_135.^2) ./ (dA32_0_90.^2 + dB32_0_90.^2) );

% Im_{23,32} = atan2( dB23*dA32 - dA23*dB32  /  dA23*dA32 + dB23*dB32 )
Im_23_32 = atan2( dB23_45_135.*dA32_0_90 - dA23_45_135.*dB32_0_90, ...
                  dA23_45_135.*dA32_0_90 + dB23_45_135.*dB32_0_90 );

% |CB| = sqrt( (Re_{23,32})^2 + (Im_{23,32})^2 )
absCB = sqrt( Re_23_32.^2 + Im_23_32.^2 );

% arg[CB] = atan2( Im_{23,32} / Re_{23,32} )
argCB = atan2( Im_23_32, Re_23_32 );

% CB = Re_{23,32} + i*Im_{23,32}
OUT = struct('mod', absCB, 'arg', argCB, 'cplx', Re_23_32 + 1i*Im_23_32);
end
