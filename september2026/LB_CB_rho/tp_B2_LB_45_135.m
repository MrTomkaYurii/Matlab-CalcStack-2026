function OUT = tp_B2_LB_45_135(f24, f42)
% TP_B2_LB_45_135  Блок B.2 (зелена формула, Word стор.2): LB_{45,135} = ln(f24/f42).
%   Незалежний блок — жодних залежностей від інших файлів Кроку B.
%   Імена змінних = позначення з Word, щоб порівнювати рядок-в-рядок:
%
%       Word                             код
%       f^c_24, f^c_42                   f24, f42         (вхід, Крок A)
%       dA_24^{RC,LC}, dB_24^{RC,LC}     dA24_RCLC, dB24_RCLC   = Re(f24), Im(f24)
%       dA_42^{0,90},  dB_42^{0,90}      dA42_0_90, dB42_0_90   = Re(f42), Im(f42)
%       Re_{24,42}, Im_{24,42}           Re_24_42, Im_24_42
%       |LB_{45,135}|, arg[LB_{45,135}]  absLB_45_135, argLB_45_135
%   (Верхні індекси RC,LC / 0,90 у Word — з яких освітлень зібрано f24 і
%   f42; це робить Крок A (tp_fik_pair.m), тут беремо готові f24, f42.)
%
%   Вхід : f24, f42 — комплексні (число або 2D-карта, з tp_fik_pair.m).
%   Вихід: OUT = struct('mod',|LB_45,135|, 'arg',arg[LB_45,135], 'cplx',Re+i*Im)
%
%   Ділення на нуль: СВІДОМО без епсилона (IEEE-754 NaN/Inf, далі isfinite).

% Захист від мовчазного неявного розширення (N×1 з 1×N -> N×N): розміри мусять збігатися.
assert(isequal(size(f24), size(f42)), 'tp_B2_LB_45_135: f24 і f42 мають бути одного розміру');

% f^c_mn = dA_mn + i*dB_mn   =>   dA = Re(f), dB = Im(f)
dA24_RCLC = real(f24);    dB24_RCLC = imag(f24);
dA42_0_90 = real(f42);    dB42_0_90 = imag(f42);

% Re_{24,42} = 1/2 * ln( ( (dA24)^2 + (dB24)^2 ) / ( (dA42)^2 + (dB42)^2 ) )
Re_24_42 = 0.5 * log( (dA24_RCLC.^2 + dB24_RCLC.^2) ./ (dA42_0_90.^2 + dB42_0_90.^2) );

% Im_{24,42} = atan2( dB24*dA42 - dA24*dB42  /  dA24*dA42 + dB24*dB42 )
Im_24_42 = atan2( dB24_RCLC.*dA42_0_90 - dA24_RCLC.*dB42_0_90, ...
                  dA24_RCLC.*dA42_0_90 + dB24_RCLC.*dB42_0_90 );

% |LB_{45,135}| = sqrt( (Re_{24,42})^2 + (Im_{24,42})^2 )
absLB_45_135 = sqrt( Re_24_42.^2 + Im_24_42.^2 );

% arg[LB_{45,135}] = atan2( Im_{24,42} / Re_{24,42} )
argLB_45_135 = atan2( Im_24_42, Re_24_42 );

% LB_{45,135} = Re_{24,42} + i*Im_{24,42}
OUT = struct('mod', absLB_45_135, 'arg', argLB_45_135, 'cplx', Re_24_42 + 1i*Im_24_42);
end
