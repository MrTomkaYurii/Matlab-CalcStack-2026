function [Re, Im, modulus, argument] = tp_B0_cross_log_ratio(A1, B1, A2, B2)
% TP_B0_CROSS_LOG_RATIO  Крок B.0 (crossLogRatio) з "Теорія поляризаційно-
%   кореляційна томографія" + claude_code_prompt_LB_CB_rho.md.
%   Модуль і аргумент ln(z1/z2) для z1=A1+iB1 (ЧИСЕЛЬНИК),
%   z2=A2+iB2 (ЗНАМЕННИК), через явну дійсну/уявну частину — буквальна
%   реалізація (не просто log(z1./z2), хоч це й еквівалентно, перевірено
%   в verify/verify_theory_formulas.m):
%
%       Re = 0.5 * ln( (A1^2+B1^2) / (A2^2+B2^2) )
%       Im = atan2( B1*A2 - A1*B2,  A1*A2 + B1*B2 )
%       modulus  = sqrt(Re^2 + Im^2)
%       argument = atan2(Im, Re)
%
%   Векторизовано: A1,B1,A2,B2 — масиви однакового розміру (числа або
%   2D-карти); усі операції поелементні.
%
%   Ділення на нуль (|z2|^2 = A2^2+B2^2 = 0, тобто знаменник z2 = 0):
%   СВІДОМО не підміняється епсилоном — MATLAB за IEEE-754 дає 0/0=NaN,
%   x/0=Inf (x>0) БЕЗ помилки/винятку, а вся візуалізація нижче за течією
%   (mapPanel/histPanel у viz_maps_hist.m, tp_validate.m) вже відфільтровує
%   не-скінченні значення через isfinite(...) — так само, як для "битих"
%   нульових кадрів деінде в пайплайні (tp_load_mat.m). Підміна на епсилон
%   натомість намалювала б фіктивний "сплеск" (ln величезного числа) у
%   картах/гістограмах — це було б ГІРШЕ за прозорий NaN/Inf.

Re = 0.5 * log( (A1.^2 + B1.^2) ./ (A2.^2 + B2.^2) );
Im = atan2( B1.*A2 - A1.*B2,  A1.*A2 + B1.*B2 );   % atan2(0,0) = 0 (MATLAB-конвенція, свідомо)

modulus  = sqrt(Re.^2 + Im.^2);
argument = atan2(Im, Re);                           % atan2(0,0) = 0 (те саме)
end
