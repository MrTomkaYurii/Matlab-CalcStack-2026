function OUT = tp_B5_LB_total(LB0_90, LB45_135)
% TP_B5_LB_TOTAL  Блок B.5 (зелена формула, Word стор.4): LB = sqrt( LB_{0,90}^2 + LB_{45,135}^2 ).
%   Незалежний блок — залежить лише від ГОТОВИХ комплексних LB_{0,90} і
%   LB_{45,135} (виходи B.1 / B.2, поле .cplx), НЕ від CB чи rho.
%   Імена змінних = позначення з Word ("Співвідношення LB = ..."):
%
%       Word                                 код
%       A1 + iB1 = LB_{0,90}                 A1, B1
%       A2 + iB2 = LB_{45,135}               A2, B2
%       C = A1^2 - B1^2 + A2^2 - B2^2        C
%       D = 2(A1*B1 + A2*B2)                 D
%       LB'^2_{0,90} + LB'^2_{45,135} = C + iD   (Word пише LB' з штрихом)
%       |LB|, arg(LB)                        absLB, argLB
%   (R = sqrt(C^2+D^2) у Word — проміжне позначення; |LB| = sqrt(R).)
%
%   Вхід : LB0_90, LB45_135 — комплексні (число або 2D-карта).
%   Вихід: OUT = struct('mod',|LB|, 'arg',arg(LB), 'cplx',sqrt(C+iD))

% Захист від мовчазного неявного розширення (N×1 з 1×N -> N×N): розміри мусять збігатися.
assert(isequal(size(LB0_90), size(LB45_135)), 'tp_B5_LB_total: LB0_90 і LB45_135 мають бути одного розміру');

A1 = real(LB0_90);     B1 = imag(LB0_90);       % LB_{0,90}   = A1 + iB1
A2 = real(LB45_135);   B2 = imag(LB45_135);     % LB_{45,135} = A2 + iB2

% (A1+iB1)^2 + (A2+iB2)^2 = C + iD
C = A1.^2 - B1.^2 + A2.^2 - B2.^2;
D = 2*(A1.*B1 + A2.*B2);

% |LB| = ( (A1^2 - B1^2 + A2^2 - B2^2)^2 + 4(A1*B1 + A2*B2)^2 )^(1/4)
absLB = ( (A1.^2 - B1.^2 + A2.^2 - B2.^2).^2 + 4*(A1.*B1 + A2.*B2).^2 ) .^ (1/4);

% arg(LB) = 1/2 atan2( 2(A1*B1 + A2*B2) / (A1^2 - B1^2 + A2^2 - B2^2) )
argLB = (1/2) * atan2( 2*(A1.*B1 + A2.*B2), A1.^2 - B1.^2 + A2.^2 - B2.^2 );

% LB = sqrt(C + iD)  (головне значення комплексного кореня, Word)
OUT = struct('mod', absLB, 'arg', argLB, 'cplx', sqrt(C + 1i*D));
end
