function OUT = tp_B4_rho(LB0_90, LB45_135)
% TP_RHO  Блок B.4 (зелена формула): rho = (1/2) atan( LB_{45,135} / LB_{0,90} ).
%   Незалежний блок — залежить лише від ГОТОВИХ комплексних LB_{0,90} і
%   LB_{45,135} (виходи tp_LB_0_90.m / tp_LB_45_135.m, поле .cplx = A+iB,
%   точно Re+i*Im логарифма-відношення), НЕ від CB чи LB. Можна викликати
%   й перевіряти окремо, підставивши будь-які тестові комплексні числа.
%
%   Вхід : LB0_90, LB45_135 — комплексні (число або 2D-карта):
%          LB0_90   = A1+iB1  (ЗНАМЕННИК комплексного ділення нижче)
%          LB45_135 = A2+iB2  (ЧИСЕЛЬНИК)
%   Вихід: OUT = struct('mod',|rho|, 'arg',arg(rho), 'cplx',rho = P+iQ)

A1 = real(LB0_90);   B1 = imag(LB0_90);
A2 = real(LB45_135); B2 = imag(LB45_135);

% Ділення на (A1^2+B1^2): та сама свідома політика, що й у
% tp_cross_log_ratio.m — 0/0->NaN, x/0->Inf за IEEE-754 (без помилки),
% відфільтровується isfinite() у візуалізації нижче за течією.
den1 = A1.^2 + B1.^2;
X = (A1.*A2 + B1.*B2) ./ den1;
Y = (A1.*B2 - A2.*B1) ./ den1;

T = atan2(2*X, 1 - X.^2 - Y.^2);                       % = 4*Re(rho)
L = log( (X.^2 + (1+Y).^2) ./ (X.^2 + (1-Y).^2) );     % = 8*Im(rho)

P = T/4;   % Re(rho)
Q = L/8;   % Im(rho)

mod_ = sqrt(P.^2 + Q.^2);
arg_ = atan2(L, 2*T);   % документально ЕКВІВАЛЕНТНО atan2(Q,P) (перевірено
                         % чисельно, verify\verify_theory_formulas.m,
                         % розділ 4) — редакція формули за
                         % claude_code_prompt_LB_CB_rho.md замість
                         % хибного "atan4" з оригінального docx.

OUT = struct('mod', mod_, 'arg', arg_, 'cplx', P + 1i*Q);
end
