function Zs = tp_smooth2(Z, sigmaPx)
% TP_SMOOTH2  NaN-безпечне гаусове згладжування 2D-карти (нормована згортка).
%   ТІЛЬКИ для побудови контурних ліній (viz_sections) — не змінює жодних
%   збережених числових даних чи інших подань. Шумні реальні дані
%   (піксель-до-пікселя) інакше дають розірвані/білі "дірки" в contour(),
%   бо лінія малюється лише там, де значення перетинає рівень.
%
%   sigmaPx <= 0 -> повертає Z без змін (згладжування вимкнене).
%   NaN не "розповзаються": використовується нормована згортка (ділення на
%   згорнуту маску валідності), а не проста conv2 по Z із замінними нулями.

if nargin < 2 || sigmaPx <= 0
    Zs = Z; return;
end

mask = isfinite(Z);
Z0 = Z; Z0(~mask) = 0;

r = max(1, ceil(3*sigmaPx));
[gx, gy] = meshgrid(-r:r, -r:r);
K = exp(-(gx.^2 + gy.^2) / (2*sigmaPx^2));
K = K / sum(K(:));

num = conv2(Z0, K, 'same');
den = conv2(double(mask), K, 'same');

Zs = num ./ den;
Zs(den < 0.3) = NaN;   % замало валідних сусідів у вікні -> не екстраполюємо
end
