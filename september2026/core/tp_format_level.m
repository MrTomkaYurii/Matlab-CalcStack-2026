function s = tp_format_level(v)
% TP_FORMAT_LEVEL  Формат підпису рівня контуру, що адаптується до масштабу
%   даних — на відміну від фіксованого %.2f, який на реальних f_ik (де
%   |f| ~ 1e-6..1e-5) перетворює ВСІ підписи на "0.00", роблячи їх марними.
%   %.3g сам обирає звичайний або експоненційний запис за величиною.

if v == 0
    s = '0';
else
    s = sprintf('%.3g', v);
end
end
