function T = cfg_tz_blocks()
% CFG_TZ_BLOCKS  Блоки рисунків за ТЗ «Нові рисунки» (15.11.2026) — з УЖЕ порахованих даних.
%
%   Кожен блок = одна тканина + пара елементів + основне фазове вікно.
%   У кожному блоці:
%     Рис.1  XY, вікно W   — усі 16 модулів і аргументів (2 PNG: .mod і .arg)
%     Рис.2  OY, 0–2π      — усі 16
%     Рис.3  OY, вікно W   — усі 16
%     Рис.4  OY, 0–2π      — колонки |e1| Arg e1 |e2| Arg e2  (приклад main)
%     Рис.5  OY, вікно W   — те саме
%     Рис.6  XY, вікно W   — те саме
%     Рис.7  XY, вікно W   — |e1|(o1) |e1|(o2) Arg e1(o1) Arg e1(o2)   (o = інші два приклади)
%     Рис.8  XY, вікно W   — те саме для e2
%   Рядки Рис.4–8: 1 — карти, 2 — гістограми, 3–4 — залежно від підблоку:
%     N.1 'acf'  — 2D-АКФ + ортогональні перерізи АКФ (Δx і Δy)
%     N.2 'psd'  — 2D-спектр потужності log10 + гістограма
%     N.3 'wav'  — скалограма |W(a,b)| + перерізи при a = 10 і a = 55
%     N.4 'skel' — вейвлет-скелетон (WTMM) + гістограма |W| у максимумах
%   Аргументи — у межах 0–2π. Кегль 10–11 pt (tz_style).
%
%   Поле .enabled = false — блок не будується, доки не уточнено в авторa ТЗ (див. .note).

% ---------------------------------------------------------------- куди / звідки
T.out      = 'C:\August 2026-Results\Розрахунки - Блоки рисунків ТЗ 15.11';
T.saveRoot = '';            % '' -> як у cfg_figures (FIG.data.saveRoot = ...\Розрахунки - Двот. елем. ММ)
T.overwrite = false;        % готові PNG (+ .stats.csv) пропускаються — прогін можна перезапускати
T.docx      = true;         % Word-файли (рисунки + стат-моменти) після кожного блоку
T.dpi       = 600;

% ---------------------------------------------------------------- параметри обробки
T.wav.cutScales  = [10 55];  % ТЗ: перерізи вейвлета на a = 10 і a = 55
T.wav.scaleRange = [1 64];   % діапазон масштабів CWT (у статті було [1 40] — 55 туди не входить)
T.kinds = struct('key', {'acf','psd','wav','skel'}, ...
                 'name', {'АКФ', 'Спектри потужності', 'Вейвлети (a = 10, a = 55)', 'Скелетони'});

% ---------------------------------------------------------------- блоки
B = struct('id',{}, 'name',{}, 'sample',{}, 'main',{}, 'others',{}, 'elems',{}, 'win',{}, ...
           'enabled',{}, 'note',{});
B(end+1) = blk('1', 'М''яз',  'Мяз живота', '1', {'2','3'}, {'f33','f44'}, 1.75, true, '');
B(end+1) = blk('2', 'Серце',  'Серце',      '2', {'1','3'}, {'f33','f44'}, 1.75, false, ...
    ['У ТЗ блоку 2 немає (двічі повторено блок 3 — Мозок). Припущення: Серце. ' ...
     'Серце 1 має порожні канали — тому основний приклад 2. Увімкнути після підтвердження.']);
B(end+1) = blk('3', 'Мозок',  'Мозг',       '1', {'2','3'}, {'f33','f44'}, 1.75, true, ...
    'У Мозку всі приклади мають порожні канали: на Рис.1–3 8 панелей із 16 порожні.');
B(end+1) = blk('4', 'Мозок',  'Мозг',       '1', {'2','3'}, {'f23','f24'}, 1.75, true, ...
    'ТЗ: «Мозок 1,2,4» — прикладу 4 немає, взято 1, 2, 3.');
B(end+1) = blk('5', 'Мозок',  'Мозг',       '1', {'2','3'}, {'f21','f41'}, 1.25, false, ...
    ['f21, f41 у Мозку 1–3 ПОРОЖНІ (нулі в ex_90 / ey_0) — рисунки будуть без даних. ' ...
     'Потрібна заміна тканини (М''яз / Серце 2–3) або елементів. ТЗ: «Мозок 1,2,5» — взято 1, 2, 3.']);
T.blocks = B;
end

function b = blk(id, name, sample, main, others, elems, win, enabled, note)
b = struct('id',id, 'name',name, 'sample',sample, 'main',main, 'others',{others}, ...
           'elems',{elems}, 'win',win, 'enabled',enabled, 'note',note);
end
