function writeReadme(root)
txt = sprintf([ ...
    'СТРУКТУРА .mat-ФАЙЛІВ (двоточкова матриця Мюллера, для М. Горського)\n' ...
    '====================================================================\n\n' ...
    'ЦЕ ОПИС СХЕМИ ФОРМАТУ. Що РЕАЛЬНО зараз у теці (які зразки/кроки) —\n' ...
    'див. "Поточний стан" У КІНЦІ файлу (там і дата генерації).\n\n' ...
    'ФАЙЛ:  <Зразок>_<Приклад>_<алгоритм>.mat\n' ...
    '       <Зразок>   = Серце | Мяз_живота | Мозг      (пробіл -> підкреслення)\n' ...
    '       <Приклад>  = 1 | 2 | 3                      (повторний вимір того самого зразка)\n' ...
    '       <алгоритм> = orthogonal | generalized\n' ...
    'Окремий файл на КОЖЕН зразок x приклад x алгоритм (приклади НЕ зливаються).\n' ...
    'Усередині РІВНО ОДНА змінна, названа за алгоритмом. Обидві — вкладені\n' ...
    'структури глибиною 4:  <алгоритм>.<фазове вікно>.<напрям|крок>.<fXX>.<mod|arg>\n\n' ...
    '-- orthogonal --------------------------------------  struct, 8 полів\n' ...
    '   .phase_0to<D>deg                                фазове вікно; D = 360,315,270,225,180,135,90,45 (град)\n' ...
    '      .OX_step_<d>  /  .OY_step_<d>                напрям + крок d (px). OX: друга точка зсунута на (d,0);\n' ...
    '                                                  OY: на (0,d). Зберігаються ОКРЕМО, без злиття.\n' ...
    '         .f11 .f12 ... .f44                        16 елементів f_ik (i,k = 1..4), двоточкова матриця Мюллера\n' ...
    '            .mod   400x400 double                  |f_ik|.  Індекс = позиція ПЕРШОЇ точки пари (рядок y, стовпець x)\n' ...
    '            .arg   400x400 double                  angle(f_ik), радіани (-pi, pi]\n' ...
    '                                                  NaN = крайовий піксель без пари АБО відкинутий фазовим вікном\n\n' ...
    '-- generalized -------------------------------------  struct, 8 полів\n' ...
    '   .phase_0to<D>deg                                те саме фазове вікно (D град)\n' ...
    '      .step_<d>                                    крок сітки векторів рознесення d (px); напрям один —\n' ...
    '                                                  повний 2D-скан площини (dx, dy)\n' ...
    '         .f11 .f12 ... .f44                        16 елементів f_ik\n' ...
    '            .mod   (2M+1)x(2M+1) double            < |f_ik| > — СЕРЕДНЄ модуля по ВСІХ перших точках з таким рознесенням\n' ...
    '            .arg   (2M+1)x(2M+1) double            кругове середнє angle(f_ik) по тих самих парах\n' ...
    '                                                  Індекс = вектор рознесення (dy рядок, dx стовпець), центр = (0,0).\n' ...
    '                                                  Вісь dx,dy = -M : d : +M px,  M = floor((N-1)/d)*d  (для d=1 -> 799x799).\n' ...
    '                                                  Сама вісь у файлі НЕ зберігається. Центр (нульове рознесення) = NaN.\n\n' ...
    'СПІЛЬНЕ\n' ...
    '  D (фазове вікно): опорна фаза = arg(Ey) - arg(Ex) освітлення inRC (праве\n' ...
    '     циркулярне, азимутально інваріантне). Пікселі з опорною фазою поза\n' ...
    '     [0, D deg] відкинуті. Вужче вікно -> більше NaN (~0.2%% при 360 -> >80%% при 90).\n' ...
    '  d (крок): повний проєктний набір 1,2,4,8,16,32; у конкретному файлі —\n' ...
    '     лише вже пораховані на момент збору (часто самий step_1).\n' ...
    '  mod > 0, дуже мале (~1e-9 .. 1e-5), без фіз. одиниць (масштаб амплітуд поля).\n' ...
    '  arg — радіани в (-pi, pi].  NaN усюди = "немає даних", маскувати перед аналізом.\n\n' ...
    'Файли перезаписуються при кожному дорахунку зразка (run_TwoPoint_Pipeline)\n' ...
    'або ручному запуску run_TwoPoint_CollectForHorsky.\n' ...
    '\n']);

txt = [txt inventoryText(root)];
fid = fopen(fullfile(root,'README.txt'), 'w', 'n', 'UTF-8');
fwrite(fid, txt, 'char');
fclose(fid);
end

% ------------------------------------------------------------------------
function txt = inventoryText(root)
% Реальний перелік .mat-файлів, які ЗАРАЗ лежать у теці (не проєктна
% схема вище, а факт) — генерується щоразу заново при записі README, тож
% завжди відповідає останньому запуску збору.
d = dir(fullfile(root, '*.mat'));
names = sort({d.name});

lines = { ...
    'Поточний стан (на момент генерації цього README)', ...
    '=================================================='};
lines{end+1} = sprintf('Згенеровано: %s', datestr(now, 'yyyy-mm-dd HH:MM:SS'));
lines{end+1} = '';
if isempty(names)
    lines{end+1} = '(поки немає жодного зібраного файлу)';
else
    lines{end+1} = sprintf('%d файл(ів):', numel(names));
    for i = 1:numel(names)
        lines{end+1} = ['  ' names{i}]; %#ok<AGROW>
    end
end
txt = sprintf('%s\n', strjoin(lines, char(10)));
end
