def bullets(doc, items):
    for t in items:
        doc.add_paragraph(t, style='List Bullet')


def h(doc, text, before=10):
    para(doc, text, bold=True, size=13, before=before)


def table(doc, header, rows, widths, colors=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(header)); t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, x in enumerate(header):
        put(t.cell(0, j), x, bold=True)
    for i, r in enumerate(rows, start=1):
        for j, x in enumerate(r):
            put(t.cell(i, j), x, center=j > 0)
            if colors:
                shade(t.cell(i, j), colors[i - 1])
    for j, w in enumerate(widths):
        for r in t.rows:
            r.cells[j].width = Cm(w)
    return t


