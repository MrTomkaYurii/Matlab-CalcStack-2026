function FIG = cfg_figures()
% CFG_FIGURES  Єдине джерело налаштувань для рисунків у статтю
%   (пакет august2026\paper_figures). За аналогією з config\cfg_TwoPoint.m —
%   уся геометрія, шрифти, формати експорту й перелік варіантів тут.
%
%   Рисунки будуються НЕ з нуля: читаються вже пораховані result.mat під
%   FIG.data.saveRoot (той самий, що й у cfg_TwoPoint). Нічого не рахується
%   в f_ik — лише mod/arg-карти для панелей + моменти Z1..Z4 для таблиці.

FIG = struct();

% ------------------------------------------------------------------ вивід
%   Три рисунки у статтю (кожен — сітка 4x4, той самий охват "≡ Рис.1"):
%     Fig1  сирі 2D-карти |f|/arg + гістограми              (kind='raw')
%     Fig2  2D-АКФ тих карт          + 1D-перерізи АКФ      (kind='acf')
%     Fig3  2D-спектри потужності    + гістограми PSD        (kind='psd')
%   Кожен — у двох парах елементів (f33-f44, f23-f24) -> два скрипти в
%   теці figNN\, обидва пишуть у FIG.out.root\FigN\.
%     FIG.out.root\
%       Fig1\ color\ svg\  Fig1.f33-f44.<variant>.<sample>.ex<N>.color.svg
%             color\ pdf\|png\   ...        gray\ svg\|pdf\|png\   ... .gray. ...
%       Fig2\ ...   Fig3\ ...
%       stats.moments.txt/.docx   (Fig1: Z1..Z4)
%       stats.acf.txt/.docx       (Fig2: Z2, Z4, довжина кореляції)
%       stats.psd.txt/.docx       (Fig3: Z1..Z4)
FIG.out.root    = 'C:\August 2026-Results\Розрахунки - Скомпановані рисунки';
FIG.out.formats = {'svg','pdf','png'};   % TIFF поки не робимо; повернути 'tiff' у список для фіналу журналу
FIG.out.tiffDPI = 600;     % растровий TIFF (фінал для журналу): 300 фото / 600 змішане / 1200 штрих
FIG.out.pngDPI  = 200;     % PNG — прев'ю / вставити у Word чи лист

% ====================================================================
% ЩО САМЕ БУДУВАТИ у пакетному прогоні run_all_figures — щоб не «скопом».
%   Перелік завдань: залиш у списку те, що потрібно; прибери/закоментуй —
%   пропускається. Регістр не важливий; порядок не важливий.
%     'Fig1' .. 'Fig6'  — ОБИДВІ пари елементів рисунка (f33-f44 і f23-f24)
%     'Fig3:f23f24'      — лише одна пара цього рисунка (':f33f44' / ':f23f24')
%     'Fig7'            — повна матриця Мюллера (усі 16 елементів, один рисунок)
%     'stats'          — таблиці статистичних моментів (.txt + .docx)
%   FIG.build стосується ЛИШЕ run_all_figures. Поодинокі рисунки й далі
%   запускаються напряму:  make_fig3_f23_f24(cfg_figures())
FIG.build = { 'Fig1',
    %'Fig1', 'Fig2', 'Fig3', 'Fig4', 'Fig5', 'Fig6', 'Fig7', ...
    'stats' };

% ---------------------------------------------------------------- джерело
FIG.data.saveRoot = 'C:\August 2026-Results\Розрахунки - Двот. елем. ММ';
FIG.data.step     = 1;     % крок d (у теці step_<d>); поки порахований лише 1
%   normalize — прибрати ДОВІЛЬНИЙ масштаб реконструйованих полів із карт f_ik
%   ПЕРЕД рисунками. Реконструйовані Ex,Ey мають |E| ~ 1e-3 (нормування
%   відновлення полів — поза цим кодом), f_ik білінійні -> |f_ik| ~ 1e-6.
%   true (типово): ділити всі |f_ik| на медіану |f_11| зразка/варіанта
%     (m_ik = f_ik/f_11, скалярна нормалізація ММ); arg не міняється; сирий
%     result.mat НЕ чіпається. Реалізація: common\tp_paper_normalize.m
%   false: сирі значення ~1e-6 (тоді в підписах — "arbitrary units").
FIG.data.normalize = true;

% ------------------------------------------------------- спільний словник
% Речі, однакові для ВСІХ рисунків (не "що будувати", а "як називати/шукати").
% зразок -> короткий тег для імені файлу (латиниця, без пробілів)
FIG.sampleTag = { ...
    'Серце',      'heart'; ...
    'Мяз живота', 'muscle'; ...
    'Мозг',       'brain' };
% приклад (підтека 1/2/3) -> префікс у ІМЕНІ ФАЙЛУ. 'ex' плутає необізнану
% людину -> 'zrazok' (zrazok1, zrazok2, ...). Латиниця, без пробілів.
FIG.exampleTag = 'zrazok';

% варіанти алгоритм/напрям: tag -> як шукати result.mat (tag також іде в
%   ІМ'Я ФАЙЛУ — тому "generalized", а не скорочення "XY": цей алгоритм ще
%   не узгоджений остаточно, і в назві файлу має бути видно, який саме він).
%   generalized: saveRoot\<S>\<E>\<phase>\generalized\step_<d>\result.mat  (var R,  R.dirs{1}='step_<d>')
%   orthogonal : saveRoot\<S>\<E>\<phase>\orthogonal\<OX|OY>\step_<d>\result.mat (var Rd, Rd.dirs{1}='<OX|OY>_step_<d>')
FIG.variants = { ...
    struct('tag','generalized', 'algo','generalized', 'dir',''  ), ...
    struct('tag','OX',          'algo','orthogonal',  'dir','OX'), ...
    struct('tag','OY',          'algo','orthogonal',  'dir','OY') };

% фазові вікна = БЛОКИ рисунка (верхній -> нижній). Кожен блок = ряд карт
% + ряд гістограм під ними. Спільні для Fig1/Fig2 (та сама пара вікон).
%   glob  — маска теки під saveRoot\<S>\<E>\  (індекс фіксований: 01=2pi ... 08=0.25pi)
%   label — горизонтальний підпис НАД блоком (tex)
FIG.phase(1) = struct('glob','phase_01_*', 'label','0 - 2\pi');
FIG.phase(2) = struct('glob','phase_06_*', 'label','0 - 0.75\pi');

% ========================================================================
% КОНФІГУРАЦІЯ ОКРЕМИХ РИСУНКІВ — що САМЕ будувати: елементи, біологічні
% тканини (зразки), приклади, варіанти алгоритму. Оформлення (геометрія/
% шрифти/кольори нижче) спільне для всіх; тут — лише ОБСЯГ.
%
%   Секції: FIG.figNN_<пара>.  Кожен рисунок — у ДВОХ парах елементів
%   (f33-f24, f23-f24). За замовчуванням охват однаковий для всіх ("≡ Рис.1")
%   — щоб звузити конкретний рисунок/пару, правити його поля.
%
%   ПЕР-ФІГУРНЕ ПЕРЕВИЗНАЧЕННЯ ПАРАМЕТРІВ: у .params КОЖНОЇ секції можна
%   перекрити будь-який параметр оформлення/розрахунку САМЕ для цього
%   рисунка (глибоке злиття поверх спільних значень нижче). Напр.:
%       FIG.fig02_f33f44.params.acf.cropFrac  = 0.6;      % ширший кроп 2D-АКФ
%       FIG.fig03_f33f44.params.psd.clipPct   = 2;
%       FIG.fig06_f33f44.params.mfr.qRange    = -8:0.2:8;
%       FIG.fig05_f23f24.params.wav.scaleRange = [3 150];
%       FIG.fig01_f33f44.params.geom.histH    = 26;
% ========================================================================
S = @(elems, elemTex) struct('elems',{elems}, 'elemTex',{elemTex}, ...
        'samples',{{'Серце','Мяз живота','Мозг'}}, 'examples',{{'1','3'}}, ...
        'variants',{FIG.variants}, 'params',{struct()});

FIG.fig01_f33f44 = S({'f33','f44'}, {'f_{33}','f_{44}'});   % Fig1 (сирі карти)  — f33,f44
FIG.fig01_f23f24 = S({'f23','f24'}, {'f_{23}','f_{24}'});   % Fig1 — f23,f24
FIG.fig02_f33f44 = S({'f33','f44'}, {'f_{33}','f_{44}'});   % Fig2 (2D-АКФ)      — f33,f44
FIG.fig02_f23f24 = S({'f23','f24'}, {'f_{23}','f_{24}'});   % Fig2 — f23,f24
FIG.fig03_f33f44 = S({'f33','f44'}, {'f_{33}','f_{44}'});   % Fig3 (2D-PSD)      — f33,f44
FIG.fig03_f23f24 = S({'f23','f24'}, {'f_{23}','f_{24}'});   % Fig3 — f23,f24
FIG.fig04_f33f44 = S({'f33','f44'}, {'f_{33}','f_{44}'});   % Fig4 (вейвлет-скелетони) — f33,f44
FIG.fig04_f23f24 = S({'f23','f24'}, {'f_{23}','f_{24}'});   % Fig4 — f23,f24
FIG.fig05_f33f44 = S({'f33','f44'}, {'f_{33}','f_{44}'});   % Fig5 (вейвлет W(a,b))  — f33,f44
FIG.fig05_f23f24 = S({'f23','f24'}, {'f_{23}','f_{24}'});   % Fig5 — f23,f24
FIG.fig06_f33f44 = S({'f33','f44'}, {'f_{33}','f_{44}'});   % Fig6 (мультифрактали) — f33,f44
FIG.fig06_f23f24 = S({'f23','f24'}, {'f_{23}','f_{24}'});   % Fig6 — f23,f24

% ------------------------------------------------------- Fig7: повний набір f_ik
%   Не "пара елементів" — УСЯ матриця Мюллера на ОДНОМУ рисунку: |f_ik| зліва,
%   arg(f_ik) справа, обидва фазові вікна (блоки згори вниз). 4x(4x4)=64 панелі.
%   Один файл на варіант x зразок x приклад x кольоровий режим. Окремий макет
%   (common\render_mueller_grid.m), окремий скрипт (fig07\make_fig7_mueller.m).
FIG.fig07.samples  = {'Серце','Мяз живота','Мозг'};
FIG.fig07.examples = {'1','3'};
FIG.fig07.variants = FIG.variants;
FIG.fig07.params   = struct();   % пер-фігурне перевизначення (напр. .color.modClipPct = 2)

% --------------------------------------------------------- макет рисунка
%   16 панелей = 4 стовпці x 4 ряди:
%     ряд 1  карти,      фазове вікно 1   (a) (b) (c) (d)
%     ряд 2  гістограми  тих карт          (e) (f) (g) (h)
%     ряд 3  карти,      фазове вікно 2   (i) (j) (k) (l)
%     ряд 4  гістограми  тих карт          (m) (n) (o) (p)
%   Стовпці: |f_a| , arg(f_a) , |f_b| , arg(f_b).
%   Літери (a)..(p) — ПІД кожною панеллю (найнижчий елемент клітинки).
%   Підпис фазового вікна — горизонтально НАД блоком.

% --------------------------------------------------------- макет / геометрія
%   Розмір фігури НЕ фіксуємо: беремо розмір вікна як є (FIG.geom.figSize = []).
%   Щоб зафіксувати під журнал — задати [шир_см вис_см] (напр. [18 21]).
FIG.geom.figSize = [];       % [] -> розмір вікна; [W H] см -> зафіксувати
%   Значення нижче — АБСТРАКТНІ пропорції макета (мм). Позиції осей = ці мм,
%   поділені на повний абстрактний розмір -> нормовані координати. Реальні
%   пропорції панелей залежать від співвідношення сторін вікна.
FIG.geom.aspectW     = 180;  % абстрактна повна ширина
FIG.geom.marginL     = 15;   % ліворуч: вісь y карти стовпця 1
FIG.geom.marginR     = 6;    % праворуч
FIG.geom.marginT     = 4;    % зверху — навмисно = blockGap (щоб проміжок перед "0-2pi"
                              % був такий самий, як перед "0-0.75pi")
FIG.geom.marginB     = 6;    % знизу
% colGap ВЕЛИКИЙ навмисно: кожна карта показує СВОЮ вісь y (цифри + слово
% "y (px)"), і ця вісь стоїть у проміжку ЗЛІВА від відповідної карти —
% тобто в colGap мають вміститись цифри+підпис y-осі НАСТУПНОЇ карти.
FIG.geom.colGap      = 13;
FIG.geom.phaseHdrH   = 9;    % смуга підпису фазового вікна + лінія (+ проміжок до colorbar-а)
FIG.geom.cbarStripH  = 1.8;  % кольорова смужка горизонтального colorbar-а (над кожною картою) — тонка
FIG.geom.cbarTickH   = 6;    % цифри під смужкою colorbar-а
FIG.geom.titleH      = 6;    % заголовок стовпця (|f_a|, arg(f_a))
FIG.geom.histH       = 23;   % висота ряду гістограм (вища за карту)
FIG.geom.surf3dH     = 34;   % висота ряду 3D-поверхонь (Fig2, ряди 2,4) — замість histH
% --- зона ПІД панеллю (цифри осі + підпис осі + літера) ------------------
%   Літера панелі (a)..(p) стоїть у смузі під панеллю. Смуга рахується як:
%       axisLabelH  +  letterGap  +  <висота літери>  +  letterGap
%   тобто відступ НАД літерою (від підпису осі) і ПІД літерою (до наступної
%   панелі) — ОДНАКОВІ й дорівнюють letterGap. Тримати letterGap невеликим —
%   лише щоб літера не злипалась ні з підписом осі, ні з панеллю нижче.
FIG.geom.axisLabelH  = 7.5;  % цифри осі x + назва осі безпосередньо під панеллю
                              % (виміряна висота "200 400 600" + "x (px)" при 10pt Arial)
FIG.geom.surf3dLabelH = 11;  % те саме для 3D-поверхні (проєкційні підписи нижчі)
FIG.geom.letterGap   = 2.2;  % ОДНАКОВИЙ відступ понад і під літерою панелі
FIG.geom.blockGap    = 4;    % між блоком фаз. вікна 1 і блоком 2 — навмисно = marginT

% ------------------------------------------------------------- шрифт/лінії
FIG.font.name  = 'Arial';
FIG.font.size  = 10;         % ЄДИНИЙ кегль: осі, цифри, заголовки, літери панелей
FIG.line.axis  = 0.75;       % pt, товщина рамки осей
FIG.panel.letterStyle = '(a)';   % '(a)' | 'a)' | 'a' | '(A)'
FIG.panel.letterBold  = false;   % літери під панелями — звичайні (не жирні)

% -------------------------------------------------------------- кольори
%   КОЖЕН рисунок будується у ДВОХ варіантах — 'color' і 'gray' — в окремі
%   підтеки (див. структуру виводу нижче). FIG.color.modes задає перелік.
FIG.color.modes = {'color', 'gray'};
FIG.color.maps.color = struct('mod','jet', 'arg','jet');   % кольоровий — jet (як у школі Ушенка)
FIG.color.maps.gray  = struct('mod','gray', 'arg','gray'); % ЧБ (для друку / colour-safe)
%   Прим.: у 'gray' аргумент — лінійний -pi(чорний)..+pi(білий); розрив на
%   ±pi неминучий (циклічність у відтінках сірого не передається).
FIG.color.argClim   = [-pi pi];   % фіксовані межі colorbar-а аргументу (обидва варіанти)
FIG.color.modClipPct = 0;         % 0 = сирі min/max (без нормування, за вимогою);
                                  % >0 -> межі [prctile(p) .. prctile(100-p)]
FIG.color.nan       = [1 1 1];    % колір NaN-пікселів (край без пари / поза вікном)

% --------------------------------------------------------------- осі карт
FIG.axis.unit         = 'px';     % одиниці осей карт
FIG.axis.yDir         = 'normal'; % 'normal' (y вгору) | 'reverse' (як зображення)
FIG.map.grid          = true;     % сітка поверх карт
FIG.map.gridColor     = [1 1 1];
FIG.map.gridAlpha     = 0.35;
FIG.map.nGrid         = 4;        % орієнтовно стільки поділок сітки

% --------------------------------------------------------------- гістограми
FIG.hist.nbins   = 40;            % однакові для всіх панелей одного типу -> однакова ширина стовпчиків
FIG.hist.norm    = 'count';       % 'count' (без нормування, сирі числа пікселів) | 'probability' | 'pdf'
FIG.hist.fill    = [0.55 0.55 0.55];
FIG.hist.edge    = [0 0 0];
FIG.hist.edgeW   = 0.3;           % pt

% ----------------------------------------------------- АКФ / PSD (Fig2 / Fig3)
%   Рахуються "на льоту" з тих самих сирих карт (core\tp_acf_psd.m), від
%   СИРИХ mod/arg (як у tp_analytics проєкту — щоб числа збігалися).
FIG.acf.method   = 'fast';        % 'fast' (Wiener-Khinchin) | 'direct' (xcorr2)
FIG.acf.cropFrac = 0.5;           % Fig2: показувати центральні ±(cropFrac*макс. лаг) 2D-АКФ
%   Fig2, ряди карт (1,3): 2D-АКФ + КОНТУР на рівні напівширини (0.5).
FIG.acf.hwLevel  = 0.5;           % рівень контуру напівширини на 2D-АКФ
FIG.acf.hwColor  = [0 0 0];       % колір контуру
FIG.acf.hwW      = 1.3;           % pt
%   Fig2, ряди під картами (2,4): 3D-поверхня тієї ж 2D-АКФ.
FIG.acf.surf3dN  = 90;            % цільова сітка 3D-поверхні (даунсемпл важкої АКФ)
FIG.acf.surf3dView = [-40 40];    % кут огляду 3D-поверхні [az el]
FIG.acf.surf3dEdge = [];          % [] -> без сітки, чиста кольорова поверхня (jet); або [r g b] тонка сітка
FIG.acf.cut      = 'x';           % напрям 1D-перерізу для ЧИСЛА довжини кореляції (таблиця): 'x'|'y'|'radial'
FIG.psd.cropFrac = 0.5;           % Fig3: показувати центральні ±(cropFrac*0.5) нормованої частоти
FIG.psd.log      = true;          % Fig3: показувати log10(PSD) (розкид на порядки)
FIG.psd.clipPct  = 1;             % межі colorbar-а PSD за перцентилями (0 = сирі min/max)

% ----------------------------------------------------- вейвлет W(a,b) (Fig5)
%   З 2D-карти беремо 1D-профіль, від нього CWT (Wavelet Toolbox). Ряди карт
%   Fig5 — скалограма |W(a,b)| (масштаб a x позиція b), низ — гістограми |W|.
FIG.wav.profile  = 'center_row';  % 'center_row' | 'center_col' | 'mean_row'
FIG.wav.wavelet  = 'amor';        % аналітичний вейвлет Морле (як у проєкті)
FIG.wav.voices   = 12;            % голосів на октаву
FIG.wav.scaleRange = [1 120];     % показувати масштаби a в цьому діапазоні (px)
FIG.wav.yscale   = 'log';         % вісь масштабу a: 'log' | 'linear'
FIG.wav.coiMask  = true;          % за конусом впливу |W| -> NaN (не псує гістограму/шкалу)
FIG.wav.clipPct  = 1;             % межі colorbar-а |W| за перцентилями (окремо |f| / arg)
% Fig4 (скелетон): розмір точки максимуму. Малий -> лінії тонші, не зливаються.
FIG.skel.markerSize = 1;          % площа маркера scatter (pt^2); 1..3

% ------------------------------------------------- мультифрактали (Fig6)
%   core\tp_multifractal.m (спрощений WTMM з того самого профілю карти).
%   ряд 1 — крива D(q) (спектр розмірностей); ряд 2 — спектр f(h) з Delta h.
FIG.mfr.qRange   = -5:0.2:5;      % діапазон/крок порядків q (дрібний крок біля 0 -> суцільна арка f(h))
FIG.mfr.row1     = 'Dq';          % що на ряду 1: 'Dq' | 'tau' | 'hq'
FIG.mfr.line     = [0.20 0.35 0.75];   % колір кривих
FIG.mfr.lineW    = 1.3;           % pt
FIG.mfr.marker   = 3;             % розмір маркерів на кривій (pt)
%   Осі 2D-карт Fig2/Fig3: ЗІ ЗНАКОМ, центр у 0 (лаг АКФ / частота спектра —
