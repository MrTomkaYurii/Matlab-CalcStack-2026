function CFG = cfg_TwoPoint()
% CFG_TWOPOINT  Єдине джерело всіх налаштувань конвеєра двоточкового аналізу.
%   Тут зібрані всі параметри. Щоб розширити конвеєр, зазвичай достатньо
%   відредагувати лише цей файл (додати зразок, увімкнути алгоритм, стиль
%   візуалізації) і, щонайбільше, додати один новий модуль у viz/ чи core/.
%
%   Повертає вкладену структуру CFG, яку споживає run_TwoPoint_Pipeline.

CFG = struct();

% ------------------------------------------------------------------ шляхи
% ЦЯ КОПІЯ (august2026) працює з НОВИМ комплексним форматом (.mat: ex_*/ey_*,
% готові реконструйовані Ex,Ey). Стара структура (BMP, zrazok_1/2) лишається
% недоторканою в july2026 — цей файл більше на неї не вказує.
CFG.paths.readRoot = 'C:\July 2026-Results\Зразки - старі';                 % (не використовується для source=mat)
% ПЕРЕРАХУНОК під paper_figures (нова per-element схема фазового вікна,
% tp_phase_window_element.m) — ОКРЕМА тека, щоб не змішувати з основною
% "Розрахунки - Двот. елем. ММ" (там лишається старий inRC-масков
% розрахунок і поточний тимчасовий прогін кроку 8). Поверни на основну
% теку, коли цей прицільний перерахунок більше не актуальний.
CFG.paths.saveRoot = 'C:\August 2026-Results\Розрахунки - Двот. елем. ММ';  % куди писати/звідки читати результати
CFG.paths.example  = '';   % запасний варіант (тест/сим. проходи) — не використовується для mat
CFG.paths.examples = {'1','2','3'};   % підтеки-приклади всередині кожного зразка (matRoot\<зразок>\<1|2|3>\mat\...)

% matRoot — де лежать .mat файли (ex_0.mat, ey_0.mat, ...). Структура:
% matRoot\<зразок>\<приклад>\mat\ex_0.mat, ... (тека «Зразки - нові
% (серпень 2026) mat», раніше називалась rez_cs).
% tp_load_mat.m сам толерантний і до простіших вкладеностей (без прикладу,
% без mat-підтеки, повністю плоско) — див. коментар усередині файлу.
CFG.paths.matRoot = 'C:\August 2026-Results\Зразки - нові (серпень 2026) mat';

% horskyRoot — куди run_TwoPoint_CollectForHorsky.m складає консолідовані
% .mat (по одному на зразок: Мозг.mat, ...) — ЛИШЕ дані (модуль/аргумент
% f_ik), без картинок, окремо від saveRoot, для розшарювання.
CFG.paths.horskyRoot = 'C:\August 2026-Results\MOD-ARGS-MM-Горському';

% horsky.algorithms — який(і) алгоритм(и) збирати для Горського: підмножина
% {'orthogonal','generalized','polar','XY'}. За замовчуванням усі; звузь до
% одного, якщо інший ще рахується і не хочеш чекати на нього, щоб віддати
% вже готове (напр. CFG.horsky.algorithms = {'orthogonal'};).
%   polar -> файл <Зразок>_<Приклад>_polar.mat: PERP_step_d (ЄДИНА карта,
%   комплексна сума Σ_θ f) + осьові OX/OY_step_d.
%   XY -> файл <Зразок>_<Приклад>_XY.mat: step_d (ЄДИНА карта — OX+OY
%   комплексною сумою, без усереднення; збирається з orthogonal-результату).
CFG.horsky.algorithms = {'orthogonal','XY','generalized'};   % усе, що рахується цим прогоном (без polar — його не рахуємо)

% analyticsRoot — куди наш ВЛАСНИЙ (не за ТЗ, наш бонус) аналітичний шар
% (analysis_ММ/) складає зведену числову таблицю (статистика+ACF HWHM+
% мультифрактал по кожному елементу/умові), похідні таблиці закономірностей
% і підсумкові рисунки. Окремо від saveRoot і horskyRoot.
CFG.paths.analyticsRoot = 'C:\August 2026-Results\Аналітика - Двот. елем. ММ';

% ------------------------------------------------------ джерело даних
% 'synthetic' -> згенерувати спекл-поле на льоту (дані не потрібні)
% 'real'      -> читати BMP поляризаційні зображення (старий формат)
% 'mat'       -> читати готові КОМПЛЕКСНІ Ex,Ey з .mat (новий формат, тут)
CFG.source  = 'mat';
% ЛИШЕ КОРЕКТНІ зразки. Мозг (усі 3 приклади) виключений повністю — там 2 биті
% вхідні канали (ex_90/ey_0 — нулі замість комплексних, немає інтерференційних
% смуг у сирій голограмі). Серце\1 теж битий (той самий дефект), але Серце
% рахується цілком (1,2,3) — приклад 1 просто йде з data_quality_warning.txt
% (tp_load_mat.m). Повний перелік: {'Серце','Мяз живота','Мозг'}.
CFG.samples = {'Серце', 'Мяз живота', 'Мозг'};   % назви = підтеки в matRoot (усі 3 — для порівнянності з аналітикою)

% mat.rcSource / mat.lcSource — які з освітлень liv/prav є RC і LC
% (формула (13): f_i4 = (SC(RC) - SC(LC))/2).
CFG.mat.rcSource = 'prav';    % права циркулярна
CFG.mat.lcSource = 'liv';     % ліва циркулярна
% mat.ampMin — пікселі з |Ex| або |Ey| <= ampMin стають NaN (методика п. 2.2:
% при нульовому модулі фаза не визначена). 0 = відкидати лише нулі.
CFG.mat.ampMin = 0;

% fik.phaseRef — фази полів у формулах (10)-(11):
%   'full' — повні комплексні поля, фази обох компонент в обох точках (стаття);
%   'x'    — старе соглашення: фаза Ex = 0 у кожному пікселі (як запис рівн. (20)).
CFG.fik.phaseRef = 'full';

% ------------------------------------------------------------------- обрізка
CFG.crop.size = 400;   % квадратна вирізка N x N (.mat файли — 400x400)
CFG.crop.x0   = 1;     % початок (стовпець) верхнього лівого кута
CFG.crop.y0   = 1;     % початок (рядок) верхнього лівого кута

% ------------------------------------------------- фазові вибірки (Етап 1 ТЗ)
%   ОНОВЛЕНО 02.11.2026: фазова селекція — як у статті (рівн. 20, п. 6–7,
%   S9–S10): відбір ПОЛЯ ДО розрахунку f_ik (tp_phase_window.m). Для
%   кожного освітлення w пікселі з phi_xy^(w) = arg Ey^(w) - arg Ex^(w)
%   (mod 2pi) поза [0, U_k] стають NaN, і всі алгоритми рахуються вже на
%   відібраному полі. Попередня схема (16–17.09) різала ГОТОВИЙ f_ik за
%   його власним arg і штучно звужувала розподіл Arg до ширини вікна.
%
%   Вікна [0, U_k]: U_k від upperMax (k=1, [0,2pi] = без фільтра) до
%   upperMin (k=numWindows), рівний крок: 2.00pi, 1.75pi, ..., 0.25pi.
%   Папки: phase_01_[0-2.00pi] ... phase_08_[0-0.25pi].
CFG.phase.enable    = true;
CFG.phase.numWindows = 8;
CFG.phase.upperMax  = 2*pi;      % k=1 : [0, 2.00pi] (повне коло)
CFG.phase.upperMin  = 0.25*pi;   % k=8 : [0, 0.25pi] (найвужче, біля фази 0)
CFG.phase.target    = 'field';            % 'field' — маска на полі до f_ik (стаття);
                                          % 'element' — стара схема 17.09 (ріже готовий f_ik)
CFG.phase.maskMode  = 'perIllumination';  % 'perIllumination' — кожне освітлення за своєю phi_xy (стаття);
                                          % 'reference' — одна маска за освітленням refPol
CFG.phase.refPol    = 'inRC';             % лише для maskMode = 'reference'
CFG.phase.only      = [];                 % [] = усі вікна; напр. [1 6] — лише phase_01 і phase_06

% ----------------------------------------------------- вибір алгоритму
% Будь-яка підмножина {'orthogonal','generalized','polar','XY'}; кілька — якщо кілька в списку.
% 'polar' — друга точка сканується по колу кутів навколо першої, усі напрями
%           зводяться в ЄДИНУ карту PERP комплексною сумою Σ_θ f (секція CFG.polar).
% 'XY'    — ЗВЕДЕНА карта хреста: OX + OY комплексною сумою БЕЗ усереднення
%           (документ «...с единой картой», розд. 7). Бере OX/OY з
%           orthogonal-результату, ЯКЩО він на диску (нічого не перераховує);
%           інакше рахує їх у пам'яті. 'orthogonal' у списку НЕ обов'язковий.
%           Кроки — CFG.ortho.steps.
CFG.algorithms = {'orthogonal','XY','generalized'};   % повний перерахунок (нічний прогін) — без polar (не потрібен)

% ----------------------------------------- елементи матриці Мюллера f_ik
% Типово: усі 16. Звузьте, напр. до {'f11','f22','f33','f44'}, для швидкості.
els = cell(1,16); c = 0;
for i = 1:4
    for k = 1:4
        c = c + 1; els{c} = sprintf('f%d%d', i, k);
    end
end
CFG.elements = els;

    % --------------------------------------- параметри ОРТОГОНАЛЬНОГО алгоритму
    % За документом "+Ортогонально-направленний..._x_y":
    %   для кожної r1 скануємо r2 уздовж X (d,0) та уздовж Y (0,d), без діагоналей.
    %   OX та OY рахуються й подаються окремо (без злиття).
    %   ОКРЕМА карта будується для кожного рознесення d зі списку нижче (типово —
    %   діадичний багатомасштабний набір). Вихідні напрями: OX_step_1 ... OY_step_16.
    CFG.ortho.steps   = [1];% 2 4 8 16 32];  % КРОКИ (відстані) між точками для OX/OY — лише 1 (FIG.data.step у paper_figures/cfg_figures.m жорстко =1, крок 8 фігурам не потрібен)
                                          % (окремо від gen, але той самий набір масштабів)
    CFG.ortho.posStep = 1;             % ПРОРІДЖЕННЯ перших точок (1 => усі пікселі; >1 => рідша карта)
    CFG.ortho.directions = {'OX','OY'}; % обидва напрями (result.mat для orthogonal — один
                                        % файл на весь алгоритм, R.dirs містить і OX, і OY)

    % --------------------------------------- параметри ПОЛЯРНОГО алгоритму
    %   для кожної r1 друга точка сканується по КОЛУ кутів навколо неї
    %   (theta = 0 : angleStep : angleMax-angleStep, радіус rho); усі напрями
    %   зводяться в ЄДИНУ карту PERP КОМПЛЕКСНОЮ СУМОЮ Σ_θ f (без ділення —
    %   "об'єднання без усереднення"). Плюс осьові OX (theta=0) / OY (theta=90°).
    CFG.polar.radii     = [1];   % рознесення rho (px); один лаг у v1
    CFG.polar.angleStep = 9;     % крок кута (град): 9 -> 20 напрямів на 0..180
    CFG.polar.angleMax  = 180;   % діапазон кутів (град): орієнтація pi-періодична
    CFG.polar.posStep   = 1;     % прорідження перших точок (1 => усі пікселі)
    CFG.polar.montage         = false;          % проміжні по-кутові карти -> один рисунок subplot
    CFG.polar.montageElements = {'f33','f44'}; % для яких елементів будувати той рисунок

    % --------------------------------------- параметри XY (ЗВЕДЕНА карта OX+OY)
    % 'XY' читає orthogonal-результат, тож бере CFG.ortho.steps і
    % CFG.ortho.directions (мають бути обидва OX,OY). Окрема XY-карта на крок d
    % -> тека XY/step_<d>/. Єдиний власний параметр:
    %   normalize — прибрати ДОВІЛЬНИЙ масштаб реконструйованих полів
    %     (|f_ik| ~ 1e-6, бо f_ik білінійні за |E| ~ 1e-3 — нормування
    %     відновлення поза цим кодом). true: поділити ВСІ елементи XY на ОДНЕ
    %     число — медіану |XY_11| по карті (m_ik = f_ik / f_11, скалярно) ->
    %     |f_ik| стають O(1). Це ЛИШЕ поділ на скаляр: просторова структура й
    %     arg НЕ змінюються (нічого не згладжується). Множник -> R.params.normScale.
    %     false: сирі значення ~1e-6, як в orthogonal.
    CFG.XY.normalize = true;

    % --------------------------------------- параметри УЗАГАЛЬНЕНОГО алгоритму
    % За документом "Обобщённый_алгоритм_двухточечного_сканирования".
    % ДВІ НЕЗАЛЕЖНІ ЗМІННІ:
    %
    % steps — МАСИВ кроків: на КОЖЕН крок будується окрема ρ-діаграма у своїй теці
    %   (generalized\step_1\, step_2\, ...). Крок = крок сітки рознесень.
    CFG.gen.steps    = [1];% 2 4 8 16 32];  % масив кроків (кожен -> своя тека step_N),
                                         % як у старому july2026 (шість масштабів)
    CFG.gen.posStep  = 1;    % прорідження перших точок (1 => усі пікселі)
    % Автоправило: якщо в CFG.gen.steps є крок = 1 (найважчий випадок, найгустіша
    % сітка), прорідження для НЬОГО автоматично піднімається щонайменше до 2
    % (max(posStep,2)); решта кроків використовують posStep як задано вище.
    CFG.gen.maxDist  = [];       % макс. відстань (px); [] => N-1 (повний діапазон)
    CFG.gen.excludeZero = true;  % відкинути нульову відстань (0,0)
    CFG.gen.parallel    = true;  % паралельний розрахунок (parfor, усі ядра) — для 5800H (лише engine='loop')
    % Реалізація (tp_algo_generalized_run.m): числа однакові, різниця лише в швидкості.
    CFG.gen.engine      = 'batch';   % 'batch' — зсуви пачками (GPU/CPU); 'loop' — по одному, parfor
    CFG.gen.useGPU      = 'auto';    % 'auto' — GPU NVIDIA, якщо MATLAB його бачить; true | false
    CFG.gen.precision   = 'auto';    % 'auto' — single на GPU, double на CPU; або 'single' | 'double'
    CFG.gen.batchShifts = 64;        % зсувів Δy за раз; на GPU 12 ГБ можна 128–256

% ------------------------------------------------------ контроль якості
% Якщо розподіл вироджений — він НЕ зберігається (згідно з вимогою).
CFG.qc.enable     = true;
CFG.qc.maxNaNfrac = 0.95;     % пропустити, якщо частка NaN більша за це
                              % (0.95, не 0.80: найвужче фазове вікно 0.25pi —
                              % це геометрично лише 12.5% кола; на нерівномірній
                              % тканині туди може влучити 5-8% пікселів навіть
                              % у нормі — поріг 0.80 відкидав би це вікно ВСЮДИ
                              % просто через його вузькість, не через брак даних)
CFG.qc.minStd     = 1e-9;     % пропустити майже сталі карти
% minValidPixels — абсолютний мінімум валідних пікселів для розрахунку
% статистичних моментів (analysis_ММ\tp_analytics_compute_summary.m). Коли
% maxNaNfrac такий permissive (0.95), саме ЦЕЙ поріг — головний захист від
% шуму: 3-й/4-й момент (асиметрія/ексцес) на вибірці з кількох точок —
% статистичний шум, не сигнал. N=1000 із 160000 (0.6% кадру) — надійна
% база для ексцесу (похибка оцінки різко падає проти N=50), і все одно
% "пилинка" відносно повного кадру. Нижче порогу — NaN замість шумового
% числа у result.mat/analytics_summary_table.mat.
CFG.qc.minValidPixels = 1000;

% ----------------------------------------------- перемикачі візуалізації
% Layout фігур — за ескізом (варфрейми); стиль — за old/calc_2025_vis_DvotMM.
% Перерахунок під paper_figures: усі перемикачі нижче -> false — лише
% result.mat (paper_figures будує СВОЇ рисунки напряму з нього, ці
% per-елементні картинки пайплайну йому не потрібні; буст швидкості).
% Поверни в true, якщо знадобляться самостійні картинки цього прогону.
CFG.viz.colormaps   = {'jet','gray'}; % цикл колірних мап (як у старому коді)
CFG.viz.parallel    = true;   % розпаралелити побудову графіків по f_ik (parfor, усі ядра);
                              % найповільніший етап (16 елементів × 7 подань) — раніше йшов
                              % на одному ядрі. false => послідовно (як було раніше)
CFG.viz.overview    = false;   % Частина 01: сітки 4x4 (усі 16 f_ik) на рівні кроку
CFG.viz.mapsHist    = false;   % (1) на елемент: 2x2 карти + гістограми (мод+арг)
CFG.viz.blockSummary = false;  % Блок 1 за ТЗ: карти->гістограми->АКФ ОДНІЄЮ фігурою
                              % (доповнює (1) і (4B), не замінює)
CFG.viz.surfContour = false;   % (2) на елемент: 2x2 3D-поверхні + контурні карти
CFG.viz.contour3    = false;   % (2b) на елемент: контурні лінії у 3D (contour3)
CFG.viz.blockContours = false; % Блок 3 за ТЗ: 2D контур + 3D контур ОДНІЄЮ фігурою
CFG.viz.multifractal = false;  % Блок 4 (наш бонус, не з ТЗ): спектр f(h) з WTMM
                              % (партиційна функція -> tau(q) -> f(h)), огляд ДЛЯ НАС;
                              % повний аналіз з ланцюжковим трекінгом ліній — у Горського.
                              % Додає CWT-розрахунок на елемент (як wavelet/skeleton) —
                              % вимкни (false), якщо важливіша швидкість повного прогону.

CFG.multifractal.qRange = -5:0.5:5;  % діапазон порядків q для партиційної функції
CFG.viz.wavelet     = false;   % (3) на елемент: вейвлет W(a,b) (мод+арг)
CFG.viz.acfPsd      = false;   % (4A) на елемент: 2D АКФ + 2D PSD (мод+арг)
CFG.viz.acfCuts     = false;   % (4B) на елемент: 1D перерізи ACF + їх PSD (log-log)
CFG.viz.skeleton    = false;   % (5) на елемент: вейвлет-скелетон + гістограма максимумів
CFG.viz.levelBands  = false;   % (6) на елемент: смуговий аналіз концентрації біля рівнів
                              % (маска + гістограма, окремо мод/арг), доповнює (2)
CFG.viz.statsTable  = false;   % на елемент: mean/std/skew/kurt (мод+арг) у текстовий
                              % файл <fXX>_stats.txt поряд із рисунками (Етап 2.1 ТЗ)
CFG.viz.bandLevels   = 8;     % кількість рівнів для (6) (рівномірно між min і max)
CFG.viz.bandWidthPct = 0.02;  % ширина смуги = ця частка від діапазону (max-min)
CFG.viz.histBins      = 50;   % кількість стовпців гістограми
CFG.viz.contourLevels = 6;    % кількість рівнів контурів (з підписами %.2f)
CFG.viz.contourSmoothPx = 3;  % σ (px) NaN-безпечного згладжування ЛИШЕ для ліній
                              % контуру (viz_sections) — на реальних шумних даних
