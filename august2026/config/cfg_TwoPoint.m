function CFG = cfg_TwoPoint()
% CFG_TWOPOINT  Єдине джерело всіх налаштувань конвеєра двоточкового аналізу.
%   Тут зібрані всі параметри. Щоб розширити конвеєр, зазвичай достатньо
%   відредагувати лише цей файл (додати зразок, увімкнути алгоритм, стиль
%   візуалізації) і, щонайбільше, додати один новий модуль у viz/ чи core/.
%
%   Повертає вкладену структуру CFG, яку споживає run_TwoPoint_Pipeline.

CFG = struct();

% ------------------------------------------------------------------ шляхи
% ЦЯ КОПІЯ (august2026) працює з НОВИМ комплексним форматом (.mat: ex_*/ey_*,
% готові реконструйовані Ex,Ey). Стара структура (BMP, zrazok_1/2) лишається
% недоторканою в july2026 — цей файл більше на неї не вказує.
CFG.paths.readRoot = 'C:\July 2026-Results\Зразки - старі';                 % (не використовується для source=mat)
CFG.paths.saveRoot = 'C:\August 2026-Results\Розрахунки - Двот. елем. ММ';  % куди писати
                                                                            % результати (створюється сама)
CFG.paths.example  = '';   % запасний варіант (тест/сим. проходи) — не використовується для mat
CFG.paths.examples = {'3'};   % підтеки-приклади всередині кожного зразка (rez_cs\<зразок>\<1|2|3>\mat\...)

% matRoot — де лежать .mat файли (ex_0.mat, ey_0.mat, ...). Структура:
% matRoot\<зразок>\<приклад>\mat\ex_0.mat, ... (rez_cs, серпень 2026).
% tp_load_mat.m сам толерантний і до простіших вкладеностей (без прикладу,
% без mat-підтеки, повністю плоско) — див. коментар усередині файлу.
CFG.paths.matRoot = 'C:\August 2026-Results\rez_cs';

% horskyRoot — куди run_TwoPoint_CollectForHorsky.m складає консолідовані
% .mat (по одному на зразок: Мозг.mat, ...) — ЛИШЕ дані (модуль/аргумент
% f_ik), без картинок, окремо від saveRoot, для розшарювання.
CFG.paths.horskyRoot = 'C:\August 2026-Results\Дані матриці Мюллера (віддати Горському)';

% horsky.algorithms — який(і) алгоритм(и) збирати для Горського: підмножина
% {'orthogonal','generalized'}. За замовчуванням обидва; звузь до одного,
% якщо інший ще рахується і не хочеш чекати на нього, щоб віддати вже
% готове (напр. CFG.horsky.algorithms = {'orthogonal'};).
CFG.horsky.algorithms = {'orthogonal','generalized'};

% analyticsRoot — куди наш ВЛАСНИЙ (не за ТЗ, наш бонус) аналітичний шар
% (analysis/) складає зведену числову таблицю (статистика+ACF HWHM+
% мультифрактал по кожному елементу/умові), похідні таблиці закономірностей
% і підсумкові рисунки. Окремо від saveRoot і horskyRoot.
CFG.paths.analyticsRoot = 'C:\August 2026-Results\Аналітика - Двот. елем. ММ';

% ------------------------------------------------------ джерело даних
% 'synthetic' -> згенерувати спекл-поле на льоту (дані не потрібні)
% 'real'      -> читати BMP поляризаційні зображення (старий формат)
% 'mat'       -> читати готові КОМПЛЕКСНІ Ex,Ey з .mat (новий формат, тут)
CFG.source  = 'mat';
CFG.samples = {'Серце'}; %, 'Мяз живота',  'Мозг'};   % назви = підтеки в matRoot (rez_cs); повний обсяг.
                                % Мозг (усі 3 приклади) і Серце\1 мають 2 биті вхідні канали
                                % (ex_90/ey_0 — нулі замість комплексних, немає інтерференційних
                                % смуг у сирій голограмі) — рішення: рахувати як є (0+0i),
                                % НЕ пропускати; tp_load_mat.m пише data_quality_warning.txt
                                % у теку прикладу. Див. README "Known data-quality issue".

% mat.rcSource — яке з двох нових освітлень (liv/prav) використати як "RC"
% (старій формулі розділу 4 потрібне рівно ОДНЕ RC-освітлення).
CFG.mat.rcSource = 'prav';    % 'prav' або 'liv'

% ------------------------------------------------------------------- обрізка
CFG.crop.size = 400;   % квадратна вирізка N x N (.mat файли — 400x400)
CFG.crop.x0   = 1;     % початок (стовпець) верхнього лівого кута
CFG.crop.y0   = 1;     % початок (рядок) верхнього лівого кута

% ------------------------------------------------- фазові вибірки (Етап 1 ТЗ)
%   "У комплексних полях виділяється фазова вибірка — від 0-2пи до 0-0.25пи":
%   опорна фаза delta_ref = angle(Ey)-angle(Ex) каналу CFG.phase.refPol
%   (спільна для ВСІХ 4 освітлень), нормована в [0,2pi). Вікно k -> [0, U_k],
%   U_k спадає від upperMax (k=1, фактично без фільтра) до upperMin
%   (k=numWindows, найвужче) РІВНИМ кроком 0.25*pi (8 вікон: 2.00pi, 1.75pi,
%   1.50pi, 1.25pi, 1.00pi, 0.75pi, 0.50pi, 0.25pi — "адекватні", округлі
%   межі, а не довільні десяткові). Пікселі поза вікном -> NaN у Ex,Ey ВСІХ
%   освітлень (tp_phase_window.m) -> просто відкидаються при розрахунку.
CFG.phase.enable    = true;
CFG.phase.numWindows = 8;
CFG.phase.upperMax  = 2*pi;      % k=1 : [0, 2.00pi]
CFG.phase.upperMin  = 0.25*pi;   % k=8 : [0, 0.25pi]
CFG.phase.refPol    = 'inRC';    % опорне освітлення для delta_ref — праве циркулярне
                                 % (inRC -> CFG.mat.rcSource='prav'), НЕ довільний вибір:
                                 % за літературою цієї ж наукової школи (Ushenko et al.,
                                 % Two-point Stokes vector..., IOP 2020; Mueller matrix
                                 % polarization interferometry..., Frontiers 2023) саме
                                 % циркулярне освітлення є "азимутально інваріантним" —
                                 % вимір не залежить від довільної орієнтації тканини/
                                 % приладу, на відміну від лінійних 0/45/90.

% ----------------------------------------------------- вибір алгоритму
% Будь-яка підмножина {'orthogonal','generalized'}; обидва — якщо обидва в списку.
CFG.algorithms = {'generalized'};%,'orthogonal'};

% ----------------------------------------- елементи матриці Мюллера f_ik
% Типово: усі 16. Звузьте, напр. до {'f11','f22','f33','f44'}, для швидкості.
els = cell(1,16); c = 0;
for i = 1:4
    for k = 1:4
        c = c + 1; els{c} = sprintf('f%d%d', i, k);
    end
end
CFG.elements = els;

    % --------------------------------------- параметри ОРТОГОНАЛЬНОГО алгоритму
    % За документом "+Ортогонально-направленний..._x_y":
    %   для кожної r1 скануємо r2 уздовж X (d,0) та уздовж Y (0,d), без діагоналей.
    %   OX та OY рахуються й подаються окремо (без злиття).
    %   ОКРЕМА карта будується для кожного рознесення d зі списку нижче (типово —
    %   діадичний багатомасштабний набір). Вихідні напрями: OX_step_1 ... OY_step_16.
    CFG.ortho.steps   = [1];% 2 4 8 16 32];  % КРОКИ (відстані) між точками для OX/OY
                                          % (окремо від gen, але той самий набір масштабів)
    CFG.ortho.posStep = 1;             % ПРОРІДЖЕННЯ перших точок (1 => усі пікселі; >1 => рідша карта)
    CFG.ortho.directions = {'OX','OY'}; % обидва напрями (result.mat для orthogonal — один
                                        % файл на весь алгоритм, R.dirs містить і OX, і OY)

    % --------------------------------------- параметри УЗАГАЛЬНЕНОГО алгоритму
    % За документом "Обобщённый_алгоритм_двухточечного_сканирования".
    % ДВІ НЕЗАЛЕЖНІ ЗМІННІ:
    %
    % steps — МАСИВ кроків: на КОЖЕН крок будується окрема ρ-діаграма у своїй теці
    %   (generalized\step_1\, step_2\, ...). Крок = крок сітки рознесень.
    CFG.gen.steps    = [1];% 2 4 8 16 32];  % масив кроків (кожен -> своя тека step_N),
                                         % як у старому july2026 (шість масштабів)
    CFG.gen.posStep  = 1;    % прорідження перших точок (1 => усі пікселі)
    % Автоправило: якщо в CFG.gen.steps є крок = 1 (найважчий випадок, найгустіша
    % сітка), прорідження для НЬОГО автоматично піднімається щонайменше до 2
    % (max(posStep,2)); решта кроків використовують posStep як задано вище.
    CFG.gen.maxDist  = [];       % макс. відстань (px); [] => N-1 (повний діапазон)
    CFG.gen.excludeZero = true;  % відкинути нульову відстань (0,0)
    CFG.gen.parallel    = true;  % паралельний розрахунок (parfor, усі ядра) — для 5800H

% ------------------------------------------------------ контроль якості
% Якщо розподіл вироджений — він НЕ зберігається (згідно з вимогою).
CFG.qc.enable     = true;
CFG.qc.maxNaNfrac = 0.80;     % пропустити, якщо частка NaN більша за це
                              % (підняли з 0.60 — щоб вузькі фазові вибірки
                              % (phase_07/08 і подібні) теж будували картинки,
                              % а не пропускались повністю через розрідженість)
CFG.qc.minStd     = 1e-9;     % пропустити майже сталі карти

% ----------------------------------------------- перемикачі візуалізації
% Layout фігур — за ескізом (варфрейми); стиль — за old/calc_2025_vis_DvotMM.
CFG.viz.colormaps   = {'jet','gray'}; % цикл колірних мап (як у старому коді)
CFG.viz.parallel    = true;   % розпаралелити побудову графіків по f_ik (parfor, усі ядра);
                              % найповільніший етап (16 елементів × 7 подань) — раніше йшов
                              % на одному ядрі. false => послідовно (як було раніше)
CFG.viz.overview    = true;   % Частина 01: сітки 4x4 (усі 16 f_ik) на рівні кроку
CFG.viz.mapsHist    = true;   % (1) на елемент: 2x2 карти + гістограми (мод+арг)
CFG.viz.blockSummary = true;  % Блок 1 за ТЗ: карти->гістограми->АКФ ОДНІЄЮ фігурою
                              % (доповнює (1) і (4B), не замінює)
CFG.viz.surfContour = true;   % (2) на елемент: 2x2 3D-поверхні + контурні карти
CFG.viz.contour3    = true;   % (2b) на елемент: контурні лінії у 3D (contour3)
CFG.viz.blockContours = true; % Блок 3 за ТЗ: 2D контур + 3D контур ОДНІЄЮ фігурою
CFG.viz.multifractal = true;  % Блок 4 (наш бонус, не з ТЗ): спектр f(h) з WTMM
                              % (партиційна функція -> tau(q) -> f(h)), огляд ДЛЯ НАС;
                              % повний аналіз з ланцюжковим трекінгом ліній — у Горського.
                              % Додає CWT-розрахунок на елемент (як wavelet/skeleton) —
                              % вимкни (false), якщо важливіша швидкість повного прогону.

CFG.multifractal.qRange = -5:0.5:5;  % діапазон порядків q для партиційної функції
CFG.viz.wavelet     = true;   % (3) на елемент: вейвлет W(a,b) (мод+арг)
CFG.viz.acfPsd      = true;   % (4A) на елемент: 2D АКФ + 2D PSD (мод+арг)
CFG.viz.acfCuts     = true;   % (4B) на елемент: 1D перерізи ACF + їх PSD (log-log)
CFG.viz.skeleton    = true;   % (5) на елемент: вейвлет-скелетон + гістограма максимумів
CFG.viz.levelBands  = true;   % (6) на елемент: смуговий аналіз концентрації біля рівнів
                              % (маска + гістограма, окремо мод/арг), доповнює (2)
CFG.viz.statsTable  = true;   % на елемент: mean/std/skew/kurt (мод+арг) у текстовий
                              % файл <fXX>_stats.txt поряд із рисунками (Етап 2.1 ТЗ)
CFG.viz.bandLevels   = 8;     % кількість рівнів для (6) (рівномірно між min і max)
CFG.viz.bandWidthPct = 0.02;  % ширина смуги = ця частка від діапазону (max-min)
CFG.viz.histBins      = 50;   % кількість стовпців гістограми
CFG.viz.contourLevels = 6;    % кількість рівнів контурів (з підписами %.2f)
CFG.viz.contourSmoothPx = 3;  % σ (px) NaN-безпечного згладжування ЛИШЕ для ліній
                              % контуру (viz_sections) — на реальних шумних даних
                              % лінії інакше рвуться на плями. 0 = вимкнено (сирі
                              % дані); карти/гістограми/3D/АКФ/вейвлет не чіпаються

% ---- (4) АКФ + PSD -----------------------------------------------------
% Два підходи (обираєш тут):
%   'fast'   — Wiener–Khinchin: PSD = |FFT|^2, ACF = IFFT(PSD). Швидко.
%   'direct' — як рахується: ACF = xcorr2 (прямо), PSD = |FFT(ACF)|^2. Повільно.
CFG.acf.method = 'fast';

CFG.wavelet.name            = 'amor';   % аналітичний вейвлет Морле
CFG.wavelet.voicesPerOctave = 12;
CFG.wavelet.highlightScales = [10 50];  % a=10 (червона), a=50 (синя)
CFG.wavelet.scaleRange      = [1 100];  % показувати лише масштаби a в цьому інтервалі
                                        % (вище ~65 зазвичай сенсу не має; можна [1 65])
CFG.wavelet.profile         = 'center_row'; % 'center_row'|'center_col'|'mean_row'
CFG.wavelet.onArg           = true;     % також перетворювати профіль аргументу

% ----------------------------------------------------------- вихід/рендер
CFG.out.format     = 'png';
CFG.out.dpi        = 200;
CFG.out.closeAfter = true;        % закривати фігури після збереження (пакетний режим)

% ---------------------- фізична симуляція БТ (source = 'synthetic') -----
% Двопроменезаломна тканина: орієнтація осі theta(x,y) + затримка delta(x,y)
% + когерентний спекл. Усі 24 зображення — через один джонсів оператор.
CFG.sim.axisCorrLen    = 40;      % довжина кореляції орієнтації осі (px) — «архітектоніка»
CFG.sim.retCorrLen     = 30;      % довжина кореляції затримки (px)
CFG.sim.speckleCorrLen = 6;       % довжина кореляції спеклу (px)
CFG.sim.retMin         = 0;       % мін. затримка (рад)
CFG.sim.retMax         = pi;      % макс. затримка (рад) — сила двопроменезаломлення
CFG.sim.seed           = 7;       % зерно ГВЧ для відтворюваності
end
