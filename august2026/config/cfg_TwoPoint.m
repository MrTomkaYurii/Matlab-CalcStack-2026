function CFG = cfg_TwoPoint()
% CFG_TWOPOINT  Єдине джерело всіх налаштувань конвеєра двоточкового аналізу.
%   Щоб розширити конвеєр, зазвичай достатньо відредагувати лише цей файл.
%   Повертає вкладену структуру CFG, яку споживає run_TwoPoint_Pipeline.
%
%   ЗМІСТ (секції — згортаються в редакторі, «%%»):
%     1  ШЛЯХИ            куди читати / писати
%     2  ДЖЕРЕЛО ДАНИХ    source, зразки, RC-освітлення
%     3  ЩО РАХУВАТИ      <- АЛГОРИТМИ, елементи f_ik, обрізка
%     4  ФАЗОВІ ВІКНА
%     5  ПАРАМЕТРИ АЛГОРИТМІВ   5a generalized · 5b orthogonal · 5c polar
%     6  КОНТРОЛЬ ЯКОСТІ
%     7  ВІЗУАЛІЗАЦІЯ + аналітика (АКФ / мультифрактал / вейвлет)
%     8  ВИВІД / РЕНДЕР
%     9  ЗБІР ДЛЯ ГОРСЬКОГО
%    10  СИНТЕТИКА (source = 'synthetic')

CFG = struct();

%% 1 ─── ШЛЯХИ ────────────────────────────────────────────────────────────
% Ця копія (august2026) працює з КОМПЛЕКСНИМ форматом (.mat: ex_*/ey_*, готові
% реконструйовані Ex,Ey). Стара BMP-структура лишилась у july2026.
CFG.paths.readRoot      = 'C:\July 2026-Results\Зразки - старі';                 % (лише source='real')
CFG.paths.saveRoot      = 'C:\August 2026-Results\Розрахунки - Двот. елем. ММ';  % куди писати результати
CFG.paths.matRoot       = 'C:\August 2026-Results\rez_cs';                       % де лежать ex_*/ey_*.mat
                          % структура: matRoot\<зразок>\<приклад>\mat\ex_0.mat, ...
                          % tp_load_mat.m толерантний і до простіших вкладеностей.
CFG.paths.horskyRoot    = 'C:\August 2026-Results\MOD-ARGS-MM-Горському';        % консолідовані .mat для Горського
CFG.paths.analyticsRoot = 'C:\August 2026-Results\Аналітика - Двот. елем. ММ';   % наш аналітичний шар (analysis\)
CFG.paths.example       = '';   % запасний варіант (одиничні тест/сим. проходи) — для source=mat не використовується
CFG.paths.examples      = {'1','2','3'};   % підтеки-приклади в кожному зразку (rez_cs\<зразок>\<1|2|3>\mat\...)

%% 2 ─── ДЖЕРЕЛО ДАНИХ ────────────────────────────────────────────────────
%   'mat'       -> готові КОМПЛЕКСНІ Ex,Ey з .mat (новий формат, тут)
%   'real'      -> BMP поляризаційні зображення (старий формат)
%   'synthetic' -> згенерувати спекл-поле на льоту (секція 10; дані не потрібні)
CFG.source  = 'mat';

CFG.samples = {'Серце', 'Мяз живота', 'Мозг'};   % назви = підтеки в matRoot; повний обсяг.
%   Мозг (усі приклади) і Серце\1 мають 2 биті вхідні канали (ex_90/ey_0 — нулі:
%   у сирій голограмі немає інтерференційних смуг). Рішення: рахувати як є (0+0i),
%   НЕ пропускати; tp_load_mat.m пише data_quality_warning.txt у теку прикладу.

% mat.rcSource — яке з двох циркулярних освітлень грає роль "RC" (формулі
% розділу 4 потрібне рівно ОДНЕ RC-освітлення).
CFG.mat.rcSource = 'prav';    % 'prav' або 'liv'

%% 3 ─── ЩО РАХУВАТИ ─────────────────────────────────────────────────────
%   АЛГОРИТМИ — будь-яка підмножина. Параметри кожного — секція 5.
%     'generalized' — повна 2D ρ-діаграма: r2 по ВСІХ векторах (Δx,Δy),
%                     усереднення по перших точках (кругове для arg). Дорого (~n^4).
%     'orthogonal'  — r2 лише вздовж осей x і y, OX/OY окремо, БЕЗ злиття. ~n^3.
%     'polar'       — r2 по ПОЛЯРНІЙ сітці кутів навколо r1; усі напрями зводяться
%                     в ЄДИНУ карту PERP комплексною СУМОЮ (без ділення) +
%                     осьові OX/OY. Проміжне між orthogonal і generalized.
CFG.algorithms = {'generalized'};   % напр. {'polar'} або {'generalized','polar'}

% елементи матриці Мюллера f_ik. Типово всі 16; звузь до {'f11','f22','f33','f44'}
% для швидкості.
els = cell(1,16); c = 0;
for i = 1:4
    for k = 1:4
        c = c + 1; els{c} = sprintf('f%d%d', i, k);
    end
end
CFG.elements = els;

% обрізка вхідного поля: квадрат N x N від (x0,y0)
CFG.crop.size = 400;   % .mat файли — 400x400
CFG.crop.x0   = 1;
CFG.crop.y0   = 1;

%% 4 ─── ФАЗОВІ ВІКНА (Етап 1 ТЗ) ────────────────────────────────────────
%   Опорна фаза delta_ref = angle(Ey)-angle(Ex) каналу refPol, нормована в [0,2pi).
%   Вікно k -> [0, U_k]; U_k спадає від upperMax (k=1) до upperMin (k=numWindows)
%   рівним кроком 0.25*pi. Пікселі поза вікном -> NaN у Ex,Ey ВСІХ освітлень.
CFG.phase.enable     = true;
CFG.phase.numWindows = 8;
CFG.phase.upperMax   = 2*pi;      % k=1 : [0, 2.00pi]
CFG.phase.upperMin   = 0.25*pi;   % k=8 : [0, 0.25pi]
CFG.phase.refPol     = 'inRC';    % опорне освітлення — праве циркулярне (азимутально інваріантне,
                                  % Ushenko et al. IOP 2020 / Frontiers 2023), НЕ довільний вибір.

%% 5 ─── ПАРАМЕТРИ АЛГОРИТМІВ ────────────────────────────────────────────

% --- 5a. УЗАГАЛЬНЕНИЙ (generalized) ------------------------------------
%   steps — МАСИВ кроків сітки рознесень: на КОЖЕН своя ρ-діаграма у теці step_N.
CFG.gen.steps    = [1];        % напр. [1 2 4 8 16 32]
CFG.gen.posStep  = 1;          % прорідження перших точок (1 => усі пікселі)
%   Автоправило: якщо в gen.steps є крок = 1 (найгустіша сітка), прорідження для
%   НЬОГО автоматично >= 2 (max(posStep,2)); решта кроків — posStep як задано.
CFG.gen.maxDist     = [];      % макс. відстань (px); [] => N-1 (повний діапазон)
CFG.gen.excludeZero = true;    % відкинути нульову відстань (0,0)
CFG.gen.parallel    = true;    % parfor по стовпцях Δx

% --- 5b. ОРТОГОНАЛЬНИЙ (orthogonal) ----------------------------------
%   Для кожної r1: r2 уздовж X (d,0) та уздовж Y (0,d), без діагоналей. OX і OY
%   рахуються й зберігаються ОКРЕМО (без злиття). Окрема карта на кожне d.
CFG.ortho.steps      = [1];             % напр. [1 2 4 8 16 32]
CFG.ortho.posStep    = 1;               % прорідження перших точок
CFG.ortho.directions = {'OX','OY'};     % підмножина {'OX','OY'}

% --- 5c. ПОЛЯРНИЙ (polar) ------------------------------------------
%   Для кожної r1 друга точка сканується по колу навколо неї: кути 0..angleMax
%   кроком angleStep (deg), радіус з radii (px). f_ik усіх напрямів зводяться в
%   ЄДИНУ карту PERP комплексною СУМОЮ Σ_θ f (БЕЗ ділення). Плюс осьові OX (θ=0)
%   та OY (θ=90°). Проміжні по-кутові карти виводяться ОДНИМ рисунком (subplot).
CFG.polar.radii     = [1];              % рознесення ρ (px); одна карта PERP на кожен ρ
CFG.polar.angleStep = 9;                % крок кута, градуси (9 -> 20 напрямів на 0..180)
CFG.polar.angleMax  = 180;              % діапазон кутів, градуси (180 = півколо; орієнтація pi-періодична)
CFG.polar.posStep   = 1;                % прорідження перших точок
CFG.polar.montage         = true;       % робити рисунок по-кутових карт |f_ik(theta)| + сума
CFG.polar.montageElements = {'f33','f44'};   % для яких елементів (кожен -> свій рисунок)

%% 6 ─── КОНТРОЛЬ ЯКОСТІ ────────────────────────────────────────────────
%   Вироджений розподіл НЕ зберігається (за вимогою ТЗ).
CFG.qc.enable     = true;
CFG.qc.maxNaNfrac = 0.80;     % пропустити, якщо частка NaN більша (вузькі фазові вікна теж малюємо)
CFG.qc.minStd     = 1e-9;     % пропустити майже сталі карти

%% 7 ─── ВІЗУАЛІЗАЦІЯ + АНАЛІТИКА ───────────────────────────────────────
CFG.viz.colormaps   = {'jet','gray'};   % цикл колірних мап
CFG.viz.parallel    = true;             % parfor по f_ik (16 елементів × ~7 подань)

% -- які подання будувати (на елемент, якщо не сказано інше) --
CFG.viz.overview      = true;   % сітки 4x4 (усі 16 f_ik) на рівні кроку
CFG.viz.mapsHist      = true;   % 2x2 карти + гістограми (мод+арг)
CFG.viz.blockSummary  = true;   % Блок 1 ТЗ: карти -> гістограми -> АКФ однією фігурою
CFG.viz.surfContour   = true;   % 2x2 3D-поверхні + контурні карти
CFG.viz.contour3      = true;   % контурні лінії у 3D (contour3)
CFG.viz.blockContours = true;   % Блок 3 ТЗ: 2D контур + 3D контур однією фігурою
CFG.viz.multifractal  = true;   % Блок 4: спектр f(h) з WTMM (додає CWT-розрахунок на елемент)
CFG.viz.wavelet       = true;   % вейвлет W(a,b) (мод+арг)
CFG.viz.acfPsd        = true;   % 2D АКФ + 2D PSD (мод+арг)
CFG.viz.acfCuts       = true;   % 1D перерізи ACF + їх PSD (log-log)
CFG.viz.skeleton      = true;   % вейвлет-скелетон + гістограма максимумів
CFG.viz.levelBands    = true;   % смуговий аналіз концентрації біля рівнів
CFG.viz.statsTable    = true;   % mean/std/skew/kurt (мод+арг) -> <fXX>_stats.txt

% -- числові параметри подань --
CFG.viz.bandLevels      = 8;      % рівнів для levelBands
CFG.viz.bandWidthPct    = 0.02;   % ширина смуги = частка від (max-min)
CFG.viz.histBins        = 50;     % стовпців гістограми
CFG.viz.contourLevels   = 6;      % рівнів контурів
CFG.viz.contourSmoothPx = 3;      % σ (px) NaN-безпечного згладжування ЛИШЕ для ліній контуру (0 = вимкнено)

% -- АКФ / PSD --
CFG.acf.method = 'fast';   % 'fast' (Wiener–Khinchin) | 'direct' (xcorr2 -> |FFT|^2, повільно)

% -- мультифрактал --
CFG.multifractal.qRange = -5:0.5:5;   % діапазон порядків q для партиційної функції

% -- вейвлет --
CFG.wavelet.name            = 'amor';        % аналітичний вейвлет Морле
CFG.wavelet.voicesPerOctave = 12;
CFG.wavelet.highlightScales = [10 50];       % a=10 (червона), a=50 (синя)
CFG.wavelet.scaleRange      = [1 100];       % показувати лише масштаби a в цьому інтервалі
CFG.wavelet.profile         = 'center_row';  % 'center_row' | 'center_col' | 'mean_row'
CFG.wavelet.onArg           = true;          % також перетворювати профіль аргументу

%% 8 ─── ВИВІД / РЕНДЕР ────────────────────────────────────────────────
CFG.out.format     = 'png';
CFG.out.dpi        = 200;
CFG.out.closeAfter = true;   % закривати фігури після збереження (пакетний режим)

%% 9 ─── ЗБІР ДЛЯ ГОРСЬКОГО ────────────────────────────────────────────
% Який(і) алгоритм(и) консолідувати в horskyRoot: підмножина
% {'orthogonal','generalized','polar'}. Звузь до одного, якщо інший ще рахується.
CFG.horsky.algorithms = {'orthogonal','generalized'};

%% 10 ─── СИНТЕТИКА (source = 'synthetic') ────────────────────────────
% Двопроменезаломна тканина: орієнтація осі theta(x,y) + затримка delta(x,y) +
% когерентний спекл. Усі освітлення — через один джонсів оператор.
CFG.sim.axisCorrLen    = 40;   % довжина кореляції орієнтації осі (px)
CFG.sim.retCorrLen     = 30;   % довжина кореляції затримки (px)
CFG.sim.speckleCorrLen = 6;    % довжина кореляції спеклу (px)
CFG.sim.retMin         = 0;    % мін. затримка (рад)
CFG.sim.retMax         = pi;   % макс. затримка (рад)
CFG.sim.seed           = 7;    % зерно ГВЧ для відтворюваності
end
