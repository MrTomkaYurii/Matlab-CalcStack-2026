function [Z, m] = tp_power_moments(x)
% TP_POWER_MOMENTS  Контрольні нецентральні степеневі моменти, БЕЗ віднімання
%   середнього (методика перерахунку, розд. 3, рівн. (3)-(5); стаття (29)):
%     m_p = mean(x.^p), p = 1..4
%     Z1 = m1,  Z2 = sqrt(m2),  Z3 = m3/Z2^3,  Z4 = m4/Z2^4 (= m4/m2^2)
%   Для аргументу — дескриптори фіксованої гілки (не кругова статистика):
%   викликаюча сторона подає theta на гілці (-pi, pi].
%   Обмеження для дійсного масиву: Z4 >= 1, Z2 >= |Z1|; при x >= 0 ще Z3 >= 1.
%
%   Z : [Z1 Z2 Z3 Z4],  m : [m1 m2 m3 m4]

x = x(:);
x = x(isfinite(x));
m = nan(1,4);  Z = nan(1,4);
if isempty(x), return; end
for p = 1:4
    m(p) = mean(x.^p);
end
Z(1) = m(1);
Z(2) = sqrt(m(2));
if m(2) > 0
    Z(3) = m(3) / Z(2)^3;
    Z(4) = m(4) / Z(2)^4;
end
end
